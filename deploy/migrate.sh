#!/usr/bin/env bash
# =====================================================================
# ТАБЫС — подготовка базы при каждом запуске.
#
# ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, а не команда внутри docker-compose.yml:
# раньше пароль роли приложения задавался строкой прямо в YAML с
# экранированием кавычек. Docker подставил значение не так, как
# рассчитывалось, и в базе оказался НЕ ТОТ пароль, что у сервера.
# Ошибка вылезла не сразу: главная страница и проверка здоровья базу
# не трогают, поэтому всё выглядело работающим до первой регистрации.
# Скрипт в файле не зависит от правил экранирования — портить нечего.
#
# Что делает:
#   1) создаёт роль приложения (если её нет);
#   2) накатывает новые миграции;
#   3) синхронизирует пароль роли с настройками;
#   4) ПРОВЕРЯЕТ, что приложение реально подключается этим паролем.
#
# Шаг 4 — главный урок: не «сделали и надеемся», а «сделали и убедились».
# Если проверка не пройдёт, запуск остановится здесь, а не превратится
# в загадочную ошибку у клиента при первой попытке войти.
# =====================================================================
set -euo pipefail

echo "=== 1/4 Роль приложения"
psql -v ON_ERROR_STOP=1 -q -f /db/setup_prod.sql

echo "=== 2/4 Миграции"
bash /db/apply.sh

echo "=== 3/4 Пароль роли приложения"
if [ -z "${DB_APP_PASSWORD:-}" ]; then
  echo "ОШИБКА: DB_APP_PASSWORD пуст. Проверьте /opt/tabys/deploy/.env"
  exit 1
fi
# Пароль передаётся переменной psql, а не склейкой строк: так он не может
# «развалиться» на кавычках, какими бы знаками ни был.
# Через стандартный ввод, а не через -c: подстановка переменных psql
# работает только так (с -c psql отправляет строку как есть — проверено).
psql -v ON_ERROR_STOP=1 -q -v pw="$DB_APP_PASSWORD" <<'SQL'
ALTER ROLE shop_app PASSWORD :'pw';
SQL
echo "· пароль установлен"

echo "=== 4/4 Проверка: приложение подключается к базе"
# Обязательно по ИМЕНИ ХОСТА ИЗ НАСТРОЕК (tabys-db), а не по 127.0.0.1:
# внутри контейнера базы подключение к самой себе разрешено без пароля,
# и такая проверка проходила бы всегда, скрывая настоящую поломку.
if PGPASSWORD="$DB_APP_PASSWORD" psql -h "${PGHOST:-tabys-db}" -U shop_app -d "${PGDATABASE:-shop}" \
     -tAc "SELECT 1" > /dev/null 2>&1; then
  echo "· подключение под ролью приложения работает"
else
  echo "ОШИБКА: роль shop_app не подключается своим паролем."
  echo "Запуск остановлен намеренно — иначе сервер поднялся бы неработающим."
  exit 1
fi

echo "База готова."
