#!/usr/bin/env bash
# =====================================================================
# ТАБЫС — выложить новую версию кассы для обновления по сети.
#
# Кассы сами спросят сервер о новой версии, покажут кассиру «что нового»
# и обновятся ПО ЕГО СОГЛАСИЮ и только при закрытой смене.
#
# Использование:
#   bash 13_publish_kassa.sh /root/Tabys-Kassa-3.0.0-setup.exe 3.0.0 "Касса собрана заново"
#
# КАССА СОБИРАЕТСЯ ИЗ pos2. Прежняя лежит в pos-desktop и остаётся
# рабочей, пока клиенты не обновятся: снимать её рывком нельзя.
# =====================================================================
set -euo pipefail
FILE="${1:?укажите путь к установщику}"
VERSION="${2:?укажите версию, например 1.1.0}"
# ОПИСАНИЕ БЕРЁТСЯ ИЗ ФАЙЛА, А НЕ С КОМАНДНОЙ СТРОКИ.
#
# PowerShell портит русские буквы по дороге: кассир увидел бы «-થ»
# вместо слов. А это ЕДИНСТВЕННОЕ, что он читает перед тем, как
# согласиться остановить кассу на минуту.
#
# Файл ЧТО-НОВОГО.md едет на сервер вместе с кодом — кодировка ему не
# страшна. С командной строки описание всё ещё можно передать, но
# только латиницей.
NOTES="${3:-}"

if [ -z "$NOTES" ]; then
  ЧТО=/opt/tabys/pos2/ЧТО-НОВОГО.md
  if [ -f "$ЧТО" ]; then
    # Берём первый связный кусок под заголовком версии: это и есть
    # «что нового» для кассира.
    # Строка под знаком «>» написана коротко, для кассира.
    NOTES=$(awk '/^> /{sub(/^> /,""); print; exit}' "$ЧТО" 2>/dev/null)
  fi
  NOTES="${NOTES:-Улучшения и исправления}"
fi

UPD=/opt/tabys/deploy/updates
mkdir -p "$UPD"

[ -f "$FILE" ] || { echo "Файл не найден: $FILE"; exit 1; }
NAME="Tabys-Kassa-$VERSION-setup.exe"

echo "── Копирую установщик ($(du -h "$FILE" | cut -f1))"
cp "$FILE" "$UPD/$NAME"

# Описание пишем ПОСЛЕ файла: касса читает описание и сразу идёт за
# файлом. Обратный порядок означал бы окно, когда описание уже новое,
# а файла ещё нет — и касса получила бы ошибку скачивания.
cat > "$UPD/latest.json" <<JSON
{
  "version": "$VERSION",
  "file": "$NAME",
  "notes": "$NOTES"
}
JSON
echo "── Описание версии записано"

# Старые установщики храним, но не больше трёх: каждый весит ~270 МБ.
ls -1t "$UPD"/Tabys-Kassa-*-setup.exe 2>/dev/null | tail -n +4 | xargs -r rm -f

echo
echo "── Проверка: что отдаёт сервер"
docker compose -p tabys -f /opt/tabys/deploy/docker-compose.prod.yml up -d server >/dev/null 2>&1
sleep 3
curl -s https://tabys.duckdns.org/api/pos/update/latest | head -c 300; echo
echo
echo "ГОТОВО. Кассы предложат обновление при закрытой смене."
