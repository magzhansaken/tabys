-- =====================================================================
-- 058_owner_role_fix.sql — регистрация с сайта упала из-за моей роли.
--
-- ОТКАЗ НА ЖИВОМ СЕРВЕРЕ: «подзапрос вернул больше одной строки»,
-- регистрация клиента через сайт не проходила совсем.
--
-- ПРИЧИНА, И ОНА МОЯ. Системные роли в этой системе ОБЩИЕ: у них
-- account_id пустой, одна роль «owner» на всю базу. Регистрация берёт
-- её запросом (SELECT id FROM role WHERE code='owner') — без привязки
-- к магазину, потому что привязки и не должно быть.
--
-- А моя функция platform_create_tenant заводила СВОЮ роль «owner» на
-- каждый магазин. После первого же клиента, заведённого партнёром,
-- ролей с этим кодом стало две — и запрос регистрации сломался.
--
-- Здесь: убираем лишние роли и переводим их сотрудников на общую.
-- Саму функцию поправил, чтобы больше не создавала.
-- =====================================================================

-- Сотрудников с моих ролей переводим на общую системную.
UPDATE employee e
   SET role_id = (SELECT r.id FROM role r
                   WHERE r.code = 'owner' AND r.account_id IS NULL LIMIT 1)
 WHERE e.role_id IN (SELECT id FROM role WHERE code = 'owner' AND account_id IS NOT NULL);

-- Теперь лишние роли можно убрать.
DELETE FROM role WHERE code = 'owner' AND account_id IS NOT NULL;

-- Впредь системные коды нельзя занимать своими ролями: следующий, кто
-- захочет завести роль «owner» магазину, упрётся в запрет, а не сломает
-- регистрацию через неделю.
CREATE UNIQUE INDEX IF NOT EXISTS role_system_code_uniq
  ON role(code) WHERE account_id IS NULL;
