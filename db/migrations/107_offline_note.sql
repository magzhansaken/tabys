-- =====================================================================
-- 107_offline_note.sql — пометка «разрешено без проверки» в журнале.
--
-- ЧАСТЬ 13 РАЗБОРА ИХ КАССЫ. Их правило дословно:
--
--   «Совсем незнакомый PIN без связи — отказ пропускается с честной
--    пометкой в отчёт: гость уже отказался, зал не может ждать
--    роутер.»
--
-- Правило верное, и на кассе оно у меня уже было: без связи отмена
-- проходит, а в записи ставится «без связи, код старшего не проверен».
--
-- НО ПОМЕТКА ДО СЕРВЕРА НЕ ДОХОДИЛА. Касса её ставила, отправка
-- отбрасывала, и владелец видел обычную отмену.
--
-- А это ровно то место, где касса уязвима: интернет можно выключить
-- нарочно. Кассир дёргает провод, отменяет позиции «без проверки» —
-- и в отчёте они неотличимы от разрешённых старшим.
--
-- Теперь отличимы. Не запрет — след.
-- =====================================================================
ALTER TABLE pos_action_log
  ADD COLUMN IF NOT EXISTS offline_note text;

COMMENT ON COLUMN pos_action_log.offline_note IS
  'Как проверено разрешение, если связи не было. Пусто — проверено сервером.';

-- Имя разрешившего словами: approved_by хранит ключ сотрудника, а без
-- связи ключа может и не быть — узнали по пропуску на кассе.
ALTER TABLE pos_action_log
  ADD COLUMN IF NOT EXISTS approved_name text;

COMMENT ON COLUMN pos_action_log.approved_name IS
  'Имя разрешившего словами. Нужно, когда сервер недоступен и ключ неизвестен.';

CREATE INDEX IF NOT EXISTS pos_action_log_offline
  ON pos_action_log (account_id, at DESC)
  WHERE offline_note IS NOT NULL;
