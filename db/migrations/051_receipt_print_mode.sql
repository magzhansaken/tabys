-- =====================================================================
-- 051_receipt_print_mode.sql — Печатать ли бумажный чек.
--
-- ЗАЧЕМ. Половина покупателей у прилавка говорит «чек не надо». Лента
-- стоит денег, а рулон в кассе кончается в самый неподходящий момент —
-- посреди очереди. У МоегоСклада эта настройка есть, и она нужна.
--
-- ТРИ РЕЖИМА, а не галочка «печатать/не печатать»:
--   always — печатаем всегда (по умолчанию: так работает сейчас,
--            поведение ни у кого не меняется);
--   ask    — кассир решает при каждой продаже, кнопкой в окне оплаты;
--   never  — не печатаем, только фискальный чек уходит в налоговую.
--
-- Почему «спрашивать» отдельным режимом: в одном магазине чек нужен
-- всем (продают технику, люди носят на гарантию), в другом почти
-- никому (хлеб и молоко). Владелец знает свой случай, а кассир не
-- должен решать это за него каждый раз, если решение всегда одно.
--
-- ВАЖНО: это НЕ отключает фискализацию. Чек всё равно уходит в
-- налоговую — не печатается только бумага.
-- =====================================================================

ALTER TABLE pos_settings
  ADD COLUMN IF NOT EXISTS receipt_print_mode text NOT NULL DEFAULT 'always'
    CHECK (receipt_print_mode IN ('always', 'ask', 'never'));

COMMENT ON COLUMN pos_settings.receipt_print_mode IS
  'Бумажный чек: always — всегда, ask — кассир решает, never — не печатать. Фискализацию не отключает';
