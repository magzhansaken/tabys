-- 044_pending_registration.sql — Часть 38: регистрация с подтверждением
-- оператором вместо СМС-кода.
--
-- ПОЧЕМУ ТАК (решение владельца):
--  • СМС-шлюз в КЗ требует договора, регистрации имени отправителя и
--    согласования шаблонов — это недели. Запускаться надо сейчас.
--  • Для платного продукта с личными продажами модерация даже ЛУЧШЕ СМС:
--    владелец видит каждую заявку, звонит, договаривается о цене и
--    активирует. Так работают почти все B2B-сервисы на старте.
--  • Телефон при этом всё равно проверяется — живым звонком оператора,
--    что надёжнее автоматической СМС.
--
-- КАК УСТРОЕНО:
--  1) Новый статус аккаунта 'pending' — заявка подана, доступа ещё нет.
--  2) Регистрация: телефон + пароль + название магазина, без кода.
--  3) Вход разрешён, но кабинет показывает «ожидает активации», а API
--     отдаёт 403 на рабочие операции (кроме своих же данных и выхода).
--  4) Оператор в своей админке видит заявки и активирует одной кнопкой:
--     pending → trial (14 дней пробного периода уже начислены).
--  5) Когда подключим СМС-шлюз, вернуть автоматику можно флагом
--     REQUIRE_OTP=1 — код регистрации по коду сохранён целиком.
--
-- ВАЖНО про восстановление пароля: оно тоже шло по СМС. Пока шлюза нет,
-- пароль сбрасывает оператор (см. operator.resetPassword) — иначе
-- забытый пароль означал бы потерю доступа навсегда.
-- =====================================================================

-- Новый статус. ALTER TYPE ... ADD VALUE нельзя выполнять внутри
-- транзакции с последующим использованием, поэтому добавляем отдельно
-- и идемпотентно.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_enum e
      JOIN pg_type t ON t.oid = e.enumtypid
     WHERE t.typname = 'account_status' AND e.enumlabel = 'pending')
  THEN
    ALTER TYPE account_status ADD VALUE 'pending' BEFORE 'trial';
  END IF;
END $$;

-- Когда подана заявка и кто её обработал — для админки оператора.
ALTER TABLE account ADD COLUMN IF NOT EXISTS activated_at  timestamptz;
ALTER TABLE account ADD COLUMN IF NOT EXISTS activated_by  text;
ALTER TABLE account ADD COLUMN IF NOT EXISTS signup_note   text;   -- что написал при регистрации

-- ВАЖНО: функции, которые ИСПОЛЬЗУЮТ значение 'pending', вынесены в
-- следующую миграцию 045. PostgreSQL не разрешает пользоваться новым
-- значением перечисления в той же транзакции, где оно добавлено, а
-- apply.sh применяет каждый файл одной транзакцией. Разделение файлов —
-- и есть решение: 044 фиксирует статус, 045 им пользуется.
