-- =====================================================================
-- 048_day_start.sql — Этап 12: граница операционного дня настройкой.
--
-- ЗАЧЕМ. «День» в отчётах — не всегда календарные сутки. У ресторана
-- рядом смена идёт до утра, и у них граница 06:00: выручка ночи с
-- пятницы на субботу — это пятница, а не суббота.
--
-- У магазина обычно полночь, но не всегда: круглосуточный магазин или
-- магазин при АЗС работает так же, как общепит. Если продавец закрывает
-- смену в час ночи, при календарной границе его выручка разъезжается
-- по двум дням, и отчёт «за вчера» не сходится с деньгами в кассе.
--
-- ПОЧЕМУ НАСТРОЙКОЙ, А НЕ ЧИСЛОМ В КОДЕ: у соседнего проекта это
-- зашито числом 06:00, и любое исключение требует правки кода. Мы
-- закладываем настройку сразу — стоит это одну колонку.
--
-- Умолчание 0 (полночь) — поведение не меняется ни у кого, пока
-- владелец сам не решит иначе.
-- =====================================================================

ALTER TABLE account ADD COLUMN IF NOT EXISTS day_start_hour smallint NOT NULL DEFAULT 0
  CHECK (day_start_hour >= 0 AND day_start_hour <= 23);

COMMENT ON COLUMN account.day_start_hour IS
  'С какого часа начинается операционный день. 0 = полночь (магазин), 6 = утро (общепит, круглосуточные)';
