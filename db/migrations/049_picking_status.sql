-- =====================================================================
-- 049_picking_status.sql — единые статусы: лист отбора.
--
-- Нашлось при переводе кабинета на общий показ статусов. У листа отбора
-- статусы назывались open/done, и слово «done» в общем словаре означает
-- «Проведён» — верно для складского документа, но неверно для листа
-- отбора: там это «Собран».
--
-- Из-за этого страница склада держала СВОЙ перевод статусов тернаркой —
-- а второй перевод рано или поздно разъезжается с первым. Именно так у
-- нас уже был случай, когда проведённый документ показывался служебным
-- английским словом.
--
-- Решение: у листа отбора свои значения, не пересекающиеся по смыслу с
-- документами. Тогда перевод один на всю систему.
--   open  -> picking   (собирается)
--   done  -> picked    (собран)
-- =====================================================================

UPDATE picking_list SET status = 'picking' WHERE status = 'open';
UPDATE picking_list SET status = 'picked'  WHERE status = 'done';

ALTER TABLE picking_list ALTER COLUMN status SET DEFAULT 'picking';
COMMENT ON COLUMN picking_list.status IS 'picking — собирается, picked — собран';
