-- =====================================================================
-- 108_pair_names.sql — название магазина и кассы при привязке.
--
-- Касса пишет их В ЧЕК и показывает кассиру при входе: «Мини-маркет ·
-- Касса 2». Без этого в чеке пусто, а кассир не видит, к какому
-- магазину привязана касса — а магазинов у владельца бывает несколько.
--
-- ПОЧЕМУ ОТДЕЛЬНОЙ ФУНКЦИЕЙ, А НЕ ПРОСТЫМ ЗАПРОСОМ.
--
-- Привязка идёт ДО входа: магазин ещё не назначен, и защита строк
-- отбирает только строки своего магазина — то есть НИ ОДНОЙ.
--
-- Запрос при этом не падает, а отдаёт пусто. Я на это уже наступал:
-- «прямая правка чужих строк молчит, ноль строк — не ошибка». Проверил
-- живьём — название вправду приходило пустым.
--
-- Функция с правом обхода защиты видит нужную кассу, но ТОЛЬКО ЕЁ: по
-- ключу, который уже выдан привязкой.
-- =====================================================================
CREATE OR REPLACE FUNCTION auth_register_names(p_register uuid)
RETURNS TABLE (store_name text, register_name text)
SECURITY DEFINER SET search_path = public LANGUAGE sql STABLE AS $$
  SELECT coalesce(s.name, ''), coalesce(cr.name, '')
    FROM cash_register cr
    LEFT JOIN store s ON s.id = cr.store_id
   WHERE cr.id = p_register;
$$;
GRANT EXECUTE ON FUNCTION auth_register_names(uuid) TO shop_app;
