-- СВОЯ ЦЕНА, ДОГОВОРЁННАЯ ПРИ ЗАВЕДЕНИИ.
--
-- Партнёр приезжает к клиенту и договаривается о цене: со скидкой за
-- три точки, по знакомству, на пробу. Вписать её было НЕГДЕ — цена
-- уходила по прайсу, и разбирались через месяц из счёта.
--
-- Строки счёта заводятся только при первой оплате, а договорённость
-- есть уже сейчас. Храним её в карточке клиента: при выставлении счёта
-- она возьмётся отсюда, а владелец платформы увидит её в карточке и
-- спросит, если цена подозрительная.

ALTER TABLE tenant_card ADD COLUMN IF NOT EXISTS agreed_price integer;

COMMENT ON COLUMN tenant_card.agreed_price IS
  'Цена, о которой договорились при заведении. Пусто — по прайсу. Владелец платформы видит её в карточке';
