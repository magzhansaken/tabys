-- =====================================================================
-- 106_discount_limit.sql — предел скидки кассира.
--
-- ЧАСТЬ 4 РАЗБОРА ИХ КАССЫ. У них у каждой роли свой потолок скидки:
-- «Ваш лимит — 10% (2 400 ₸)». Дал меньше — прошло молча. Дал больше —
-- нужен код старшего.
--
-- У МЕНЯ БЫЛО «ВСЁ ИЛИ НИЧЕГО»: настройка магазина говорит, можно
-- кассиру давать скидки или нет. Можно — значит любую, хоть сто
-- процентов. Нельзя — значит зови старшего даже ради ста тенге.
--
-- Первое опасно: кассир по сговору с покупателем отдаёт товар даром, и
-- в отчёте это выглядит как обычная продажа со скидкой.
--
-- Второе изматывает: старшего зовут двадцать раз за смену из-за
-- мелочи, и он перестаёт вникать — жмёт код не глядя. Тогда охрана
-- перестаёт работать вовсе.
--
-- Потолок решает обе беды: мелочь кассир даёт сам, крупное видит
-- старший и вникает, потому что зовут редко.
--
-- ПУСТО ЗНАЧИТ БЕЗ ПРЕДЕЛА — так у владельца и администратора: им
-- потолок ни к чему, они и есть последняя подпись.
-- =====================================================================
ALTER TABLE role
  ADD COLUMN IF NOT EXISTS discount_limit_pct integer;

COMMENT ON COLUMN role.discount_limit_pct IS
  'Потолок скидки роли в процентах. Пусто — без предела (владелец, админ).';

-- Кассиру ставим десять процентов: хватает на «округлите» и «нет
-- сдачи», а раздать товар даром уже нельзя.
UPDATE role SET discount_limit_pct = 10
 WHERE code = 'cashier' AND discount_limit_pct IS NULL;

-- =====================================================================
-- Личный предел сотрудника — сильнее ролевого.
--
-- Роль даёт общий потолок, но старшему кассиру можно поднять его лично,
-- не заводя новую роль ради одного человека. У донора это отдельное
-- поле, и они правы: роли плодить хуже, чем разрешить исключение.
-- =====================================================================
ALTER TABLE employee
  ADD COLUMN IF NOT EXISTS discount_limit_pct integer;

COMMENT ON COLUMN employee.discount_limit_pct IS
  'Личный потолок скидки. Пусто — берётся от роли.';
