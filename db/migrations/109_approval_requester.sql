-- =====================================================================
-- 109_approval_requester.sql — «кто просил» может быть пустым.
--
-- НАЙДЕНО ПРОВЕРКОЙ ЖИВЬЁМ. Касса зовёт старшего подтвердить действие,
-- а сервер падает с «внутренней ошибкой»: столбец «кто просил» не
-- принимает пусто.
--
-- Пусто там бывает по делу: разрешение просят ДО входа кассира — при
-- настройке кассы, при первом запуске, при снятии блокировки. Ключа
-- кассира тогда нет вовсе.
--
-- Что видел кассир: «Сервер отвечает с ошибкой». Позицию не отменить,
-- очередь стоит, а причина — обязательный столбец, о котором никто не
-- знает.
--
-- Кто разрешил (approved_by) остаётся обязательным: без подписи запись
-- бессмысленна, и это как раз то, что спросят при разборе.
-- =====================================================================
ALTER TABLE action_approval ALTER COLUMN requested_by DROP NOT NULL;

COMMENT ON COLUMN action_approval.requested_by IS
  'Кто просил разрешения. Пусто — просили до входа кассира (настройка, первый запуск).';
