-- =====================================================================
-- 060_pay_fields.sql — реквизиты оплаты пятью полями, как у донора.
--
-- Было два поля: картинка QR и «реквизиты словами». Клиент видел
-- сплошной текст и разбирался в нём сам.
--
-- У донора пять полей, и каждое отвечает за свою строку на экране
-- клиента:
--   pay_url   — ссылка «Оплатить»: одно нажатие вместо переписывания;
--   pay_qr    — картинка QR: навёл камеру и заплатил;
--   pay_name  — получатель: клиент проверяет, туда ли платит;
--   pay_phone — номер для перевода руками, если ссылка не открылась;
--   pay_note  — что писать в комментарии, чтобы платёж нашли.
--
-- Разница житейская: «Kaspi 7777 7777 7777, получатель Магжан С.»
-- одной строкой человек копирует целиком и вставляет в поле номера —
-- перевод не проходит, и виноватой оказывается система.
-- =====================================================================
ALTER TABLE platform_settings
  ADD COLUMN IF NOT EXISTS pay_url   text,
  ADD COLUMN IF NOT EXISTS pay_name  text,
  ADD COLUMN IF NOT EXISTS pay_phone text,
  ADD COLUMN IF NOT EXISTS pay_note  text;

COMMENT ON COLUMN platform_settings.pay_url IS
  'Ссылка «Оплатить»: одно нажатие вместо переписывания номера';
COMMENT ON COLUMN platform_settings.pay_note IS
  'Что писать в комментарии к платежу, чтобы его нашли';
