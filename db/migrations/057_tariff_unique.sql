-- =====================================================================
-- 057_tariff_unique.sql — запрет повторов кода тарифа.
--
-- Причина найдена по отказу регистрации на живом сервере: «подзапрос
-- вернул больше одной строки». Регистрация берёт тариф по коду
-- 'start' — и если таких оказалось два, вставка подписки падает, а
-- вместе с ней и весь путь клиента с сайта.
--
-- Откуда взялись дубли: у поля code стоял ON CONFLICT в самой вставке,
-- но САМОГО ЗАПРЕТА в таблице не было — то есть защита работала только
-- при повторе той же миграции, а руками или другим путём дубль
-- заводился свободно.
--
-- Здесь: сначала убираем дубли, оставляя самый ранний, потом ставим
-- настоящий запрет.
-- =====================================================================
DELETE FROM tariff a
 USING tariff b
 WHERE a.code = b.code AND a.created_at > b.created_at;

CREATE UNIQUE INDEX IF NOT EXISTS tariff_code_uniq ON tariff(code);
