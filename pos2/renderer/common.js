/*
 * ОБЩИЕ МЕЛОЧИ, нужные всем.
 *
 * Здесь то, что иначе списывалось бы в каждый файл — а потом
 * расходилось бы по мелочи. Все файлы кассы грузятся на ОДНУ страницу,
 * и одно имя в двух местах ломает второй файл целиком.
 */

/* СЧЁТ ПО-РУССКИ: 1 чек, 2 чека, 5 чеков.
 *
 * Кассир читает это при каждом закрытии смены, и «3 чеков» подрывает
 * доверие к цифрам: если тут не считают как надо, то и в деньгах?
 *
 * Правило языка: 11-14 всегда «много», дальше по последней цифре. */
function plural(n, one, few, many) {
  const a = Math.abs(n) % 100;
  if (a >= 11 && a <= 14) return many;
  const b = a % 10;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

/** Разряды пробелами, без значка валюты: он ломает раскладку ленты. */
function num(v) {
  return String(Math.round(Number(v) || 0)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

if (typeof module !== 'undefined') module.exports = { plural, num };
