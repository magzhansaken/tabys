/*
 * КЛЮЧИ ЧЕКОВ — UUIDv7, растут по времени.
 *
 * Зачем. При разборе спорного дня чеки в журнале лягут ПО ПОРЯДКУ
 * сами. Со случайным ключом они идут вперемешку, и «какой чек был
 * раньше» видно только по отдельному полю времени — а его могут и не
 * вывести в выгрузке.
 *
 * ПОЧЕМУ НЕ ULID, как у донора. Я пробовал: поля ключей в базе типа
 * uuid, и ULID туда не лезет. Ни один чек не ушёл бы на сервер —
 * касса копила бы их в очереди, а отправка падала с ошибкой.
 *
 * UUIDv7 даёт и то и другое: первые знаки — время в миллисекундах,
 * вид обычного UUID, сервер принимает.
 *
 * СЧЁТЧИК ВНУТРИ МИЛЛИСЕКУНДЫ обязателен. Касса создаёт ключи подряд
 * быстрее, чем тикают часы: метка времени одинаковая, и дальше порядок
 * решал бы случай. Проверено — без счётчика три ключа подряд выходят
 * не по порядку.
 */
let lastMs = 0;
let seq = 0;

function newId() {
  const now = Date.now();
  if (now === lastMs) seq = (seq + 1) & 0xfff;   // 4096 на миллисекунду
  else { lastMs = now; seq = 0; }

  const hex = now.toString(16).padStart(12, '0');
  const r = (n) => Array.from({ length: n },
    () => '0123456789abcdef'[Math.floor(Math.random() * 16)]).join('');

  // Вид: xxxxxxxx-xxxx-7sss-yxxx-xxxxxxxxxxxx
  //   первые 12 знаков — время, потом версия 7, потом счётчик.
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-7${seq.toString(16).padStart(3, '0')}`
    + `-${'89ab'[Math.floor(Math.random() * 4)]}${r(3)}-${r(12)}`;
}

if (typeof module !== 'undefined') module.exports = { newId };
