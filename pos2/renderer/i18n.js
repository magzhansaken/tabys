const LANGS = { ru: RU, kz: KZ };

/**
 * Взять слово.
 *
 * НЕТ ПЕРЕВОДА — БЕРЁМ РУССКИЙ, а не показываем ключ. Кассир не должен
 * видеть «pin_title» на экране: это выглядит поломкой.
 */
function t(key, lang = 'ru') {
  const словарь = LANGS[lang] || RU;
  return словарь[key] || RU[key] || key;
}

/** Все ли слова переведены. Для проверки, а не для работы. */
function missing(lang) {
  const словарь = LANGS[lang];
  if (!словарь) return Object.keys(RU);
  return Object.keys(RU).filter((k) => !словарь[k]);
}

if (typeof module !== 'undefined') {
  module.exports = { RU, KZ, LANGS, t, missing };
}
