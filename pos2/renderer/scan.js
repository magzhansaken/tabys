/*
 * СКАНЕР ШТРИХКОДОВ.
 *
 * У ДОНОРА ЭТОГО НЕТ ВОВСЕ: в ресторане блюда выбирают из меню, а не
 * сканируют. Взят только их урок про поле — «курсор в поле сразу:
 * сканер начнёт печатать в ту же секунду, и кассиру не придётся
 * сначала целиться в поле пальцем».
 *
 * В магазине сканер — главный способ пробить товар. Восемь чеков из
 * десяти набираются им, а не пальцем.
 *
 * КАК УСТРОЕН СКАНЕР. Для кассы он выглядит как клавиатура: быстро
 * печатает цифры и жмёт Enter. Отличить его от человека можно ТОЛЬКО
 * по скорости — сканер шлёт знаки за миллисекунды, человек за десятые
 * доли.
 *
 * ЗАЧЕМ ОТЛИЧАТЬ. Кассир может набирать количество на цифровой
 * клавиатуре — и если считать это штрихкодом, касса начнёт искать
 * товар «12». А если считать сканер набором количества, товар не
 * пробьётся вовсе.
 */

/** Быстрее этого человек печатать не умеет. */
const SCAN_MS = 50;

/** Короче этого штрихкода не бывает: восемь знаков — самый малый. */
const MIN_LEN = 6;

/* С этого знака уже ясно: это сканер. Человек не наберёт четыре знака
   подряд быстрее пятидесяти миллисекунд каждый. */
const SURE_LEN = 4;

/**
 * ЛОВЕЦ СКАНЕРА.
 *
 * Копит знаки и решает: это сканер или человек. Отдаёт код только
 * когда уверен.
 */
function makeScanner({ onCode, minLen = MIN_LEN, maxGap = SCAN_MS }) {
  let buf = '';
  let last = 0;

  const reset = () => { buf = ''; last = 0; };

  return {
    reset,

    /**
     * Принять знак.
     *
     * @returns true — знак съеден сканером, до полей не дойдёт.
     */
    key(e, now = Date.now()) {
      const gap = last ? now - last : 0;

      // Пауза длиннее скорости сканера — начинаем заново: человек
      // печатал, потом взял сканер.
      if (last && gap > maxGap) buf = '';

      if (e.key === 'Enter') {
        const code = buf;
        reset();
        if (code.length >= minLen) {
          onCode(code);
          return true;      // Enter от сканера — не «нажал кнопку»
        }
        return false;
      }

      // Сканеры шлют цифры; буквы бывают в кодах маркировки.
      if (e.key.length !== 1) return false;

      buf += e.key;
      last = now;

      /* ЗНАК СЪЕДАЕМ, КОГДА УЖЕ ЯСНО, ЧТО ЭТО СКАНЕР.
       *
       * Найдено ЖИВЬЁМ. Кассир не печатает — курсор стоит в поле
       * поиска, и знаки сканера уходили туда. Поле слало событие
       * ввода, экран перерисовывался на КАЖДОЙ цифре, и товар,
       * положенный в чек по Enter, затирался следующей перерисовкой.
       *
       * Первые знаки пропускаем: может, это человек печатает. Но как
       * только набралось быстро и много — это сканер, столько подряд
       * за такое время человек не напечатает. */
      const этоСканер = buf.length >= SURE_LEN && gap && gap <= maxGap;
      return этоСканер;
    },

    /** Что накопилось — для проверок. */
    get buffer() { return buf; },
  };
}

/*
 * ШТРИХКОД ВЕСОВ.
 *
 * Весы в магазине печатают свой штрихкод: в нём код товара и вес. Тогда
 * кассиру не надо ни искать товар, ни вводить вес — одно движение
 * сканером, и в чеке «Яблоки, 0,450 кг».
 *
 * Разбор по казахстанскому обычаю (он же российский):
 *   22 XXXXX YYYYY K
 *   ├─ 22     префикс весового товара (бывает 20-29)
 *   │  XXXXX  код товара в весах (PLU)
 *   │  YYYYY  вес в граммах
 *   └─ K      контрольный знак
 *
 * ПРЕФИКС НАСТРАИВАЕТСЯ: у одних магазинов 22, у других 21 или 20.
 * Зашивать одно значение — обречь часть клиентов на ручной ввод.
 */
function parseWeighted(code, { prefixes = ['20', '21', '22'] } = {}) {
  const c = String(code || '').trim();
  if (!/^\d{13}$/.test(c)) return null;
  if (!prefixes.includes(c.slice(0, 2))) return null;

  const plu = String(Number(c.slice(2, 7)));      // ведущие нули убираем
  const grams = Number(c.slice(7, 12));

  /* Ноль граммов — весы не взвесили. Товар в чек не берём: цена вышла
     бы нулевая, и покупатель унёс бы его даром. */
  if (!grams) return null;

  return { plu, qty: grams / 1000, grams };
}

/**
 * ЧТО ДЕЛАТЬ С ОТСКАНИРОВАННЫМ.
 *
 * Три случая, и все три должны быть разобраны:
 *   штрихкод весов → товар и вес;
 *   обычный штрихкод → товар, количество 1;
 *   ничего не нашли → сказать словами, а не молчать.
 */
function resolveScan(code, catalog, opts = {}) {
  const c = String(code || '').trim();
  if (!c) return { ok: false, said: 'Пустой штрихкод' };

  // Сперва весовой: его код тоже цифровой и мог бы совпасть с обычным.
  const w = parseWeighted(c, opts);
  if (w) {
    const good = catalog.find((g) => String(g.plu || '') === w.plu);
    if (!good) {
      return {
        ok: false,
        said: `Весовой товар с кодом ${w.plu} не найден в каталоге. `
          + 'Позовите владельца — товар не заведён или не обновился',
      };
    }
    return { ok: true, good, qty: w.qty, from: 'весы' };
  }

  const good = catalog.find((g) => (g.barcodes || []).some((b) => String(b) === c));
  if (good) return { ok: true, good, qty: 1, from: 'штрихкод' };

  /* НЕ НАЙДЕНО. Говорим код целиком: кассир продиктует его владельцу
     по телефону, и тот заведёт товар. Без кода разговор бесполезен. */
  return {
    ok: false,
    said: `Товар со штрихкодом ${c} не найден. Продиктуйте код владельцу — `
      + 'он заведёт товар в кабинете',
    code: c,
  };
}

if (typeof module !== 'undefined') {
  module.exports = { makeScanner, parseWeighted, resolveScan, SCAN_MS, MIN_LEN, SURE_LEN };
}
