/*
 * МАРКИРОВКА: коды «Честного знака».
 *
 * Табак, пиво, вода, обувь. У каждой пачки свой код Data Matrix, и
 * продать её без кода нельзя: касса обязана передать код в налоговую,
 * иначе товар не выйдет из оборота.
 *
 * У ДОНОРА ЭТОГО НЕТ ВОВСЕ: в ресторане не маркируют. Строю по разбору
 * старой кассы, где нашлись две беды подряд.
 *
 * ГЛАВНОЕ ПРАВИЛО, ВЫСТРАДАННОЕ ДВАЖДЫ:
 *
 *   ОДНА СВЁРТКА НА ВСЕ ПУТИ. В части 5 я починил кнопку «−», а в
 *   части 15 оказалось, что ввод цифрами идёт другим путём — и та же
 *   беда там осталась.
 *
 *   Было 3 бутылки и 3 считанные марки. Убрали одну — осталось ДВЕ
 *   бутылки и ТРИ марки. Лишняя ушла бы в налоговую как проданная, а
 *   товар стоит на полке. Разбираться владельцу, и доказать он ничего
 *   не сможет.
 */

/**
 * Сколько марок ещё нужно строке.
 *
 * По ЦЕЛЫМ штукам: полбутылки не бывает, а вот полкило сыра — бывает,
 * но сыр не маркируют. Округляем вверх на всякий случай.
 */
function needMarks(line) {
  if (!line || !line.marked) return 0;
  const надо = Math.max(0, Math.ceil(Number(line.qty) || 0));
  return Math.max(0, надо - (line.codes || []).length);
}

/** Сколько марок не хватает во всём чеке. */
function marksMissing(cart) {
  return (cart || []).reduce((a, l) => a + needMarks(l), 0);
}

/**
 * СНЯТЬ ЛИШНИЕ МАРКИ. Одна свёртка на все пути уменьшения.
 *
 * Снимаем ПОСЛЕДНИЕ считанные: их проще пересканировать, если кассир
 * передумает — пачка ещё у него в руках.
 *
 * @returns сколько сняли (0 — ничего не делали)
 */
function trimMarks(line) {
  if (!line || !line.marked || !Array.isArray(line.codes)) return 0;
  const надо = Math.max(0, Math.ceil(Number(line.qty) || 0));
  if (line.codes.length <= надо) return 0;
  const снято = line.codes.length - надо;
  line.codes.length = надо;
  return снято;
}

/**
 * РАЗОБРАТЬ КОД МАРКИРОВКИ.
 *
 * Data Matrix длинный и с разделителями. Нам нужен GTIN — первые 14
 * знаков после «01»: по нему находим товар.
 *
 * Проверять весь код не наше дело: это делает налоговая. Наше —
 * привязать код к верному товару и не дать продать чужую марку.
 */
function parseMark(raw) {
  const s = String(raw || '').trim();
  if (s.length < 20) return null;              // слишком коротко для марки

  // «01» + 14 знаков GTIN. Разделители бывают разные — берём начало.
  const m = s.match(/^01(\d{14})/);
  if (!m) return null;

  return { gtin: m[1], code: s };
}

/**
 * ПРИНЯТЬ МАРКУ В ЧЕК.
 *
 * Четыре отказа, и каждый объясняет себя:
 *   не марка вовсе;
 *   эта марка уже в чеке;
 *   товара с таким GTIN в чеке нет;
 *   все марки для этого товара уже собраны.
 */
function takeMark(cart, raw) {
  const m = parseMark(raw);
  if (!m) return { ok: false, said: 'Это не марка — отсканируйте Data Matrix на пачке' };

  /* ЭТА МАРКА УЖЕ В ЧЕКЕ. Кассир сканирует одну пачку дважды: первый
     раз не пикнуло, он повторил. Без проверки в чеке окажутся две
     марки на одну пачку — и налоговая увидит продажу того, чего нет. */
  for (const l of cart) {
    if ((l.codes || []).includes(m.code)) {
      return { ok: false, said: 'Эта марка уже в чеке — сканируйте следующую пачку' };
    }
  }

  /* Ищем строку, которой марка подходит: тот же товар и марок ещё не
     хватает. GTIN сверяем со штрихкодом товара — они совпадают. */
  const строка = cart.find((l) => l.marked && needMarks(l) > 0
    && (l.barcodes || []).some((b) => String(b) === m.gtin
      || String(b).padStart(14, '0') === m.gtin));

  if (!строка) {
    // Может, товар в чеке есть, но марки уже собраны?
    const собран = cart.find((l) => l.marked
      && (l.barcodes || []).some((b) => String(b) === m.gtin
        || String(b).padStart(14, '0') === m.gtin));
    if (собран) {
      return { ok: false,
        said: `Для «${собран.name}» все марки уже собраны — добавьте товар, если пачек больше` };
    }
    return { ok: false, said: 'Товара с этой маркой нет в чеке — сперва пробейте его' };
  }

  строка.codes = [...(строка.codes || []), m.code];

  const осталось = needMarks(строка);
  return {
    ok: true,
    line: строка,
    left: осталось,
    said: осталось
      ? `Марка принята · осталось отсканировать: ${осталось}`
      : 'Марки собраны — можно к оплате',
  };
}

/**
 * МОЖНО ЛИ К ОПЛАТЕ.
 *
 * Отказ НАЗЫВАЕТ ТОВАР. «Не все марки отсканированы» не говорит ни
 * сколько, ни у какого товара — кассир при очереди ищет глазами по
 * всему чеку.
 */
function marksReady(cart) {
  const мало = (cart || []).filter((l) => needMarks(l) > 0);
  if (!мало.length) return { ok: true };

  const всего = мало.reduce((a, l) => a + needMarks(l), 0);
  const кто = мало.map((l) => `${l.name} (${needMarks(l)})`).join(', ');

  return { ok: false, left: всего, said: `Осталось отсканировать марок: ${всего} — ${кто}` };
}

if (typeof module !== 'undefined') {
  module.exports = { needMarks, marksMissing, trimMarks, parseMark, takeMark, marksReady };
}
