/*
 * МАРКИРОВКА: сбор кодов и снятие их вместе с товаром.
 *
 * У ДОНОРА ЭТОГО НЕТ ВОВСЕ: в ресторане блюда не маркируют. Здесь всё
 * своё, но выстрадано в этом же чате.
 *
 * Что такое марка. На каждой пачке сигарет, бутылке водки, паре обуви
 * стоит свой код Data Matrix. Касса считывает его и передаёт в
 * налоговую: этот товар продан, из оборота вышел.
 *
 * ГЛАВНАЯ БЕДА, НАЙДЕННАЯ ДВАЖДЫ.
 *
 * Было 3 бутылки и 3 считанные марки. Кассир убрал одну — осталось
 * 2 бутылки и ТРИ марки. Лишняя ушла бы в налоговую как проданная, а
 * товар стоит на полке. Разбираться пришлось бы владельцу, и доказать
 * он бы ничего не смог.
 *
 * Первый раз я починил кнопку «−» и НЕ ЗАМЕТИЛ, что ввод цифрами идёт
 * другой дорогой. Та же беда, просто с другой кнопки.
 *
 * ПОЭТОМУ ЗДЕСЬ ОДНА СВЁРТКА НА ВСЕ ПУТИ. Кто бы ни уменьшил
 * количество — кнопка, цифры, удаление строки — марки приводятся в
 * порядок в одном месте.
 */

/** Сколько марок ещё нужно собрать по строке. */
function needMarks(line) {
  if (!line || !line.marked) return 0;
  return Math.max(0, Math.ceil(line.qty) - (line.codes || []).length);
}

/** Сколько марок не хватает по всему чеку. */
function marksMissing(cart) {
  return cart.reduce((a, l) => a + needMarks(l), 0);
}

/**
 * ПРИВЕСТИ МАРКИ В ПОРЯДОК ПОСЛЕ ИЗМЕНЕНИЯ КОЛИЧЕСТВА.
 *
 * ОДНА СВЁРТКА НА ВСЕ ПУТИ: кнопка «−», ввод цифрами, удаление строки,
 * пересчёт веса. Правило живёт в одном месте — правишь одно, не
 * забываешь другое.
 *
 * Снимаем ПОСЛЕДНЮЮ считанную: она считана позже всех, значит её
 * проще пересканировать, если кассир передумает.
 *
 * @returns сколько марок снято (0 — ничего не тронули)
 */
function trimMarks(line) {
  if (!line || !line.marked || !Array.isArray(line.codes)) return 0;
  const need = Math.max(0, Math.ceil(line.qty));
  if (line.codes.length <= need) return 0;

  const off = line.codes.length - need;
  line.codes.length = need;
  return off;
}

/** То же по всему чеку — после любой правки количества. */
function trimAll(cart) {
  return cart.reduce((a, l) => a + trimMarks(l), 0);
}

/**
 * ПРИНЯТЬ ОТСКАНИРОВАННУЮ МАРКУ.
 *
 * Кассир сканирует Data Matrix на пачке. Надо понять, к какой строке
 * она относится, и не дать записать её дважды.
 */
function addMark(cart, code, { gtinOf } = {}) {
  const c = String(code || '').trim();
  if (!c) return { ok: false, said: 'Пустой код марки' };

  /* ТА ЖЕ МАРКА ДВАЖДЫ — самая частая ошибка кассира: он не заметил,
     что первый скан прошёл, и провёл пачку ещё раз.
     Если не поймать, в чеке окажется две марки на одну бутылку, и
     вторая уйдёт в налоговую как проданная — а бутылка одна. */
  for (const l of cart) {
    if ((l.codes || []).includes(c)) {
      return { ok: false, said: 'Эта марка уже в чеке — сканируйте следующую штуку' };
    }
  }

  /* К КАКОЙ СТРОКЕ. В коде марки зашит штрихкод товара — по нему и
     находим строку. Если разбор не задан, берём первую строку, которой
     марок не хватает: у кассира в чеке обычно один маркированный вид. */
  const gtin = gtinOf ? gtinOf(c) : null;

  const подходит = (l) => needMarks(l) > 0
    && (!gtin || (l.barcodes || []).some((b) => String(b).endsWith(gtin)));

  const line = cart.find(подходит);

  if (!line) {
    // Марка есть, а товара в чеке нет — кассир забыл пробить сам товар.
    const есть = cart.some((l) => l.marked);
    return {
      ok: false,
      said: есть
        ? 'Все марки для этого товара уже собраны — проверьте количество'
        : 'Сначала пробейте сам товар, потом сканируйте марку на пачке',
    };
  }

  line.codes = line.codes || [];
  line.codes.push(c);

  const left = marksMissing(cart);
  return {
    ok: true, line, left,
    said: left
      ? `Марка принята · осталось отсканировать: ${left}`
      : 'Марки собраны — можно к оплате',
  };
}

/**
 * МОЖНО ЛИ К ОПЛАТЕ.
 *
 * Отказ ОБЯЗАН называть товар. «Не все марки отсканированы» не говорит
 * ни сколько осталось, ни у какого товара — кассир при очереди ищет
 * глазами по всему чеку.
 */
function payBlock(cart) {
  const left = marksMissing(cart);
  if (!left) return null;

  const кто = cart.filter((l) => needMarks(l) > 0)
    .map((l) => `${l.name} (${needMarks(l)})`).join(', ');

  return `Осталось отсканировать марок: ${left} — ${кто}`;
}

/**
 * ЧТО ПОКАЗАТЬ В ПОЛОСЕ НАД ЧЕКОМ.
 *
 * Кассир должен видеть состояние марок, не считая строки глазами.
 */
function markBar(cart) {
  const есть = cart.some((l) => l.marked);
  if (!есть) return null;

  const left = marksMissing(cart);
  return left
    ? { kind: 'need', title: `Нужно марок: ${left}`,
        note: 'Отсканируйте Data Matrix на каждой штуке — без кода чек нельзя' }
    : { kind: 'ok', title: 'Марки собраны',
        note: 'Коды уйдут в чеке и выведут товар из оборота' };
}

if (typeof module !== 'undefined') {
  module.exports = { needMarks, marksMissing, trimMarks, trimAll, addMark, payBlock, markBar };
}
