/*
 * ПРОВЕРКА ВОЗРАСТА.
 *
 * Мировой стандарт для всех, кто продаёт табак и алкоголь: касса
 * НАПОМИНАЕТ кассиру спросить документ. Без напоминания он не спросит —
 * при очереди не до того, а покупатель выглядит взрослым.
 *
 * В Казахстане продажа табака и алкоголя несовершеннолетнему — штраф
 * до 200 МРП на продавца и приостановка торговли для магазина. Кассир
 * при этом отвечает лично.
 *
 * ПОЧЕМУ НЕ ХВАТАЕТ МАРКИРОВКИ. Марка говорит «этот товар подлежит
 * учёту», а не «спроси документ». Пиво маркируется, а водка местного
 * розлива может и нет — но возраст спрашивать надо у обоих.
 */

/** С какого возраста что продаётся. */
const AGE_RULES = {
  tobacco: { years: 21, what: 'табак' },
  alcohol: { years: 21, what: 'алкоголь' },
  beer:    { years: 21, what: 'пиво' },
  energy:  { years: 18, what: 'энергетик' },
};

/**
 * Нужно ли спрашивать документ за этот чек.
 *
 * Считаем по ВСЕМУ чеку, а не по каждому товару: спросить один раз
 * при закрытии лучше, чем дёргать на каждой бутылке.
 */
function ageCheck(cart) {
  const нужно = [];
  let лет = 0;

  for (const l of cart || []) {
    /* Правило берём из ВИДА маркировки товара, а не из названия:
       «Пиво безалкогольное» по названию тоже пиво, а документ у него
       спрашивать незачем. */
    const r = AGE_RULES[l.marking] || (l.ageLimit ? { years: l.ageLimit, what: l.name } : null);
    if (!r) continue;

    лет = Math.max(лет, r.years);
    if (!нужно.includes(r.what)) нужно.push(r.what);
  }

  if (!лет) return { need: false };

  return {
    need: true,
    years: лет,
    what: нужно,
    /* Год рождения считаем САМИ и называем: кассир не должен вычитать
       в уме при очереди — ошибётся и продаст. */
    bornBefore: new Date().getFullYear() - лет,
    said: `В чеке ${нужно.join(', ')} — спросите документ. `
      + `Продажа с ${лет} лет: год рождения ${new Date().getFullYear() - лет} или раньше`,
  };
}

/**
 * Кассир ответил на вопрос.
 *
 * ОТКАЗ — ЭТО НЕ ОШИБКА. Покупатель без документа или младше: товар
 * снимается с чека, а не пробивается. Касса помогает кассиру, а не
 * мешает.
 */
function ageAnswer(cart, ok) {
  if (ok) return { ok: true, cart };

  /* Снимаем ТОЛЬКО возрастные позиции. Хлеб и молоко покупатель
     заберёт — незачем гонять его из очереди целиком. */
  const остаток = (cart || []).filter((l) => !AGE_RULES[l.marking] && !l.ageLimit);
  const снято = (cart || []).length - остаток.length;

  return {
    ok: false,
    cart: остаток,
    said: снято
      ? `Убрано из чека: ${снято} ${plural(снято, 'позиция', 'позиции', 'позиций')}. `
        + 'Остальное можно пробить'
      : 'Нечего убирать',
  };
}

if (typeof module !== 'undefined') {
  // eslint-disable-next-line global-require
  var { plural } = require('./common.js');
  module.exports = { AGE_RULES, ageCheck, ageAnswer };
}
