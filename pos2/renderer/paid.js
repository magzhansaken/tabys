/*
 * ЭКРАН ПОСЛЕ ОПЛАТЫ.
 *
 * Их довод взят целиком:
 *
 *   «Раньше экран сбрасывался мгновенно: чек ушёл в принтер, а кассир
 *    оставался перед пустым заказом. Если гость спрашивал "сколько
 *    сдачи?" или "а что вошло?", ответить было нечем — только искать в
 *    чеках.
 *
 *    Теперь на несколько секунд остаётся итог: номер, сумма, сдача
 *    крупно и состав. СДАЧА — САМОЕ БОЛЬШОЕ НА ЭКРАНЕ: её называют
 *    вслух, и ошибиться тут дороже всего.
 *
 *    Закрывается само через восемь секунд или по нажатию: очередь не
 *    должна ждать, пока кассир дочитает.»
 *
 * В прошлой моей кассе экрана не было вовсе: корзина очищалась, и на
 * вопрос «сколько сдачи?» приходилось искать в чеках смены.
 */

/** Сколько держим. Их число, и оно верное: прочитать успевают, очередь ждёт немного. */
const HOLD_MS = 8000;

/* ── СУММА ПРОПИСЬЮ ───────────────────────────────────────────────
 *
 * Их находка. Кассир называет сдачу вслух, а покупатель слышит через
 * шум магазина. «Триста восемьдесят» слышно вернее, чем «380»
 * прочитанное с экрана вверх ногами.
 *
 * И при споре прописью не переспорить: цифру можно прочесть как 30 или
 * 380, слово — нет.
 */
const ЕДИНИЦЫ = ['', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];
const ЖЕНСКИЕ = ['', 'одна', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];
const ДЕСЯТКИ = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят',
  'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто'];
const ОТ10ДО19 = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать',
  'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать'];
const СОТНИ = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот',
  'шестьсот', 'семьсот', 'восемьсот', 'девятьсот'];

/** Счёт по-русски: 1 тенге, 2 тенге, 5 тенге; 1 тысяча, 2 тысячи, 5 тысяч. */
function plural(n, one, few, many) {
  const a = Math.abs(n) % 100;
  if (a >= 11 && a <= 14) return many;
  const b = a % 10;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

/** Тройка знаков словами. Женский род для тысяч: «две тысячи». */
function triple(n, женский) {
  const out = [];
  const с = Math.floor(n / 100);
  const о = n % 100;
  if (с) out.push(СОТНИ[с]);
  if (о >= 10 && о <= 19) out.push(ОТ10ДО19[о - 10]);
  else {
    const д = Math.floor(о / 10);
    const е = о % 10;
    if (д) out.push(ДЕСЯТКИ[д]);
    if (е) out.push((женский ? ЖЕНСКИЕ : ЕДИНИЦЫ)[е]);
  }
  return out.join(' ');
}

function moneyInWords(sum) {
  const t = Math.floor(Math.abs(Number(sum) || 0));
  if (!t) return 'ноль тенге';

  const млн = Math.floor(t / 1000000);
  const тыс = Math.floor((t % 1000000) / 1000);
  const ост = t % 1000;
  const части = [];

  if (млн) части.push(triple(млн, false), plural(млн, 'миллион', 'миллиона', 'миллионов'));
  if (тыс) части.push(triple(тыс, true), plural(тыс, 'тысяча', 'тысячи', 'тысяч'));
  if (ост) части.push(triple(ост, false));

  части.push(plural(t, 'тенге', 'тенге', 'тенге'));
  return части.filter(Boolean).join(' ');
}

/**
 * ЧТО ПОКАЗАТЬ ПОСЛЕ ОПЛАТЫ.
 *
 * Сдача — главное. Если сдачи нет, главным становится сумма: кассиру
 * всё равно надо убедиться, что чек закрыт.
 */
function paidView(receipt, { printFailed = false } = {}) {
  const сдача = Math.round(Number(receipt.change) || 0);
  const позиций = (receipt.items || []).length;

  return {
    number: receipt.number,
    total: receipt.total,
    positions: позиций,
    change: сдача,

    /* ГЛАВНОЕ НА ЭКРАНЕ. Сдача крупнее суммы: её называют вслух, и
       ошибка здесь — либо недостача в ящике, либо обиженный
       покупатель у кассы. */
    hero: сдача > 0 ? 'change' : 'total',
    heroLabel: сдача > 0 ? 'Сдача' : 'Оплачено',
    heroAmount: сдача > 0 ? сдача : receipt.total,
    heroWords: сдача > 0 ? moneyInWords(сдача) : null,

    /* ЧЕК НЕ НАПЕЧАТАЛСЯ, А ОПЛАТА ПРОШЛА — их правило.
       Самое опасное сочетание: кассир думает, что ничего не вышло, и
       пробивает чек ЗАНОВО. Покупатель платит дважды. */
    printFailed: !!printFailed,
    printNote: printFailed
      ? 'Чек не напечатался, но ОПЛАТА ПРОШЛА. Не пробивайте заново — '
        + 'нажмите «Повторить печать»'
      : null,

    holdMs: HOLD_MS,
  };
}

/*
 * ДИСПЛЕЙ ПОКУПАТЕЛЯ — второй экран, повёрнутый к очереди.
 *
 * У донора его нет: в ресторане счёт приносят на стол. В магазине
 * покупатель стоит напротив и должен видеть, что ему пробивают —
 * иначе он не доверяет кассе и пересчитывает чек у выхода.
 *
 * Показываем ровно три вещи: последний товар, итог и сдачу. Больше на
 * такой экран не влезет, а меньше — бесполезно.
 */
function displayView({ cart, due, receipt, change: сдача }) {
  if (receipt) {
    return {
      mode: 'paid',
      total: receipt.total,
      change: Math.round(Number(сдача != null ? сдача : receipt.change) || 0),
      words: moneyInWords(Math.round(Number(сдача != null ? сдача : receipt.change) || 0)),
    };
  }

  const last = cart && cart.length ? cart[cart.length - 1] : null;
  return {
    mode: cart && cart.length ? 'sale' : 'idle',
    lastName: last ? last.name : null,
    lastQty: last ? last.qty : null,
    lastSum: last ? Math.round(last.price * last.qty) - (last.discount || 0) : null,
    positions: cart ? cart.length : 0,
    total: Number(due) || 0,
  };
}

if (typeof module !== 'undefined') {
  module.exports = { HOLD_MS, moneyInWords, plural, paidView, displayView };
}
