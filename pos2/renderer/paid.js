/*
 * ЭКРАН ПОСЛЕ ОПЛАТЫ И ДИСПЛЕЙ ПОКУПАТЕЛЮ.
 *
 * Их довод дословно:
 *
 *   «Раньше экран сбрасывался мгновенно: чек ушёл в принтер, а кассир
 *    оставался перед пустым заказом. Если гость спрашивал "сколько
 *    сдачи?" или "а что вошло?", ответить было нечем — только искать в
 *    чеках.
 *
 *    Сдача — САМОЕ БОЛЬШОЕ НА ЭКРАНЕ: её называют вслух, и ошибиться
 *    тут дороже всего.
 *
 *    Закрывается само через восемь секунд или по нажатию: очередь не
 *    должна ждать, пока кассир дочитает.»
 *
 * И их же находка про пропись: «сдачу называют вслух, и "сорок пять"
 * вместо "четыреста пятьдесят" — обычная ошибка в шуме зала».
 *
 * В магазине шума не меньше, а очередь длиннее.
 */

/** Сколько держать экран. Восемь секунд — их число, и оно верное. */
const HOLD_MS = 8000;

/*
 * СУММА ПРОПИСЬЮ.
 *
 * Кассир говорит «сдача четыреста пятьдесят», а покупатель слышит
 * «сорок пять» — и уходит, недосчитавшись. Пропись под цифрой снимает
 * спор до того, как он начался.
 */
const ЕДИНИЦЫ = ['', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];
const ЖЕНСКИЕ = ['', 'одна', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];
const ДЕСЯТЬ = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать',
  'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать'];
const ДЕСЯТКИ = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят',
  'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто'];
const СОТНИ = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот',
  'шестьсот', 'семьсот', 'восемьсот', 'девятьсот'];

/** Счёт по-русски: 1 тенге, 2 тенге, 5 тенге — но 1 тысяча, 2 тысячи. */
function plural(n, one, few, many) {
  const a = Math.abs(n) % 100;
  if (a >= 11 && a <= 14) return many;
  const b = a % 10;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

function tripletWords(n, женский) {
  const out = [];
  const с = Math.floor(n / 100);
  const д = Math.floor((n % 100) / 10);
  const е = n % 10;

  if (с) out.push(СОТНИ[с]);
  if (д === 1) {
    out.push(ДЕСЯТЬ[е]);
  } else {
    if (д) out.push(ДЕСЯТКИ[д]);
    if (е) out.push((женский ? ЖЕНСКИЕ : ЕДИНИЦЫ)[е]);
  }
  return out.join(' ');
}

/**
 * Сумма прописью, до миллиона: больше в магазине не бывает.
 */
function moneyInWords(sum) {
  const n = Math.max(0, Math.round(Number(sum) || 0));
  if (!n) return 'ноль тенге';

  const млн = Math.floor(n / 1000000);
  const тыс = Math.floor((n % 1000000) / 1000);
  const ост = n % 1000;

  const части = [];
  if (млн) части.push(`${tripletWords(млн, false)} ${plural(млн, 'миллион', 'миллиона', 'миллионов')}`);
  // Тысяча — женского рода: «две тысячи», а не «два тысячи».
  if (тыс) части.push(`${tripletWords(тыс, true)} ${plural(тыс, 'тысяча', 'тысячи', 'тысяч')}`);
  if (ост) части.push(tripletWords(ост, false));

  const слова = части.join(' ').replace(/\s+/g, ' ').trim();
  return `${слова} ${plural(n, 'тенге', 'тенге', 'тенге')}`;
}

/**
 * ЧТО ПОКАЗАТЬ ПОСЛЕ ОПЛАТЫ.
 *
 * Сдача крупнее суммы нарочно: её называют вслух, и ошибка стоит
 * дороже — либо недостача в ящике, либо обиженный покупатель.
 */
function paidView(receipt) {
  const сдача = Math.round(Number(receipt.change) || 0);
  return {
    number: receipt.number,
    positions: (receipt.items || []).length,
    total: receipt.total,
    change: сдача,
    // Пропись только для сдачи: итог покупатель видит на ценниках, а
    // сдачу слышит от кассира.
    changeWords: сдача > 0 ? moneyInWords(сдача) : null,
    title: сдача > 0 ? 'Сдача' : 'Без сдачи',
    holdMs: HOLD_MS,
  };
}

/*
 * ДИСПЛЕЙ ПОКУПАТЕЛЮ — второй экран, повёрнутый к очереди.
 *
 * Покупатель видит, что пробивают, и ловит ошибку сразу: «я это не
 * брал». Спор у кассы дешевле спора после чека.
 *
 * Отдельным окном: на кассовом компьютере обычно два выхода, и второй
 * смотрит в зал.
 */
function displayView({ cart, cartDiscount, receipt, lineSum, cartTotal }) {
  // После оплаты — итог и сдача: покупатель считает деньги в руке.
  if (receipt) {
    return {
      mode: 'paid',
      total: receipt.total,
      change: Math.round(Number(receipt.change) || 0),
      changeWords: receipt.change > 0 ? moneyInWords(receipt.change) : null,
    };
  }

  // Пока набирают — последние строки и растущий итог.
  const rows = (cart || []).slice(-6).map((l) => ({
    name: l.name,
    qty: l.qty,
    unit: l.unit || 'шт',
    sum: lineSum(l),
  }));

  return {
    mode: cart && cart.length ? 'sale' : 'idle',
    rows,
    hidden: Math.max(0, (cart || []).length - 6),
    discount: cartDiscount || 0,
    total: cart ? cartTotal(cart, cartDiscount) : 0,
  };
}

if (typeof module !== 'undefined') {
  module.exports = { HOLD_MS, moneyInWords, plural, paidView, displayView };
}
