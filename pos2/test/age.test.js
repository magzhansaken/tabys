/*
 * ПРОВЕРКА ВОЗРАСТА.
 *
 * В Казахстане продажа табака и алкоголя несовершеннолетнему — штраф
 * до 200 МРП на продавца ЛИЧНО.
 */
const { AGE_RULES, ageCheck, ageAnswer } = require('../renderer/age.js');
const { addToCart } = require('../renderer/cart.js');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };

console.log('═══ ВОЗРАСТ ═══\n');

// ── ОБЫЧНЫЙ ЧЕК НЕ ТРОГАЕМ ─────────────────────────────────────────
{
  const r = ageCheck([{ name: 'Хлеб' }, { name: 'Молоко' }]);
  ok(!r.need, '★ Хлеб и молоко — документ не спрашиваем');
  ok(!ageCheck([]).need, 'Пустой чек тоже');
}

// ── ТАБАК И АЛКОГОЛЬ ───────────────────────────────────────────────
{
  const r = ageCheck([{ name: 'Хлеб' }, { name: 'Сигареты', marking: 'tobacco' }]);
  ok(r.need && r.years === 21, '★ Сигареты — спрашиваем, с 21 года');
  ok(/спросите документ/i.test(r.said), 'И сказано прямо');

  /* ГОД РОЖДЕНИЯ СЧИТАЕМ САМИ. Кассир не должен вычитать в уме при
     очереди — ошибётся и продаст. */
  ok(r.bornBefore === new Date().getFullYear() - 21,
     `★ Год рождения посчитан: ${r.bornBefore} — кассир не вычитает в уме`);
  ok(String(r.said).includes(String(r.bornBefore)), 'И назван в подсказке');
}

// ── НЕСКОЛЬКО ВИДОВ ────────────────────────────────────────────────
{
  const r = ageCheck([
    { name: 'Пиво', marking: 'beer' },
    { name: 'Водка', marking: 'alcohol' },
    { name: 'Сигареты', marking: 'tobacco' },
  ]);
  ok(r.what.length === 3, `★ Названы все три: ${r.what.join(', ')}`);
  ok(r.years === 21, 'Берём СТАРШИЙ предел из всех');
}

// ── СПРАШИВАЕМ ПО ВИДУ, А НЕ ПО НАЗВАНИЮ ───────────────────────────
{
  const r = ageCheck([{ name: 'Пиво безалкогольное' }]);
  ok(!r.need,
     '★ «Пиво безалкогольное» — по названию пиво, а документ не нужен: смотрим ВИД товара');
}

// ── СВОЙ ПРЕДЕЛ У ТОВАРА ───────────────────────────────────────────
{
  const r = ageCheck([{ name: 'Энергетик', ageLimit: 18 }]);
  ok(r.need && r.years === 18, 'Свой предел у товара работает');
}

// ── ОТКАЗ — НЕ ОШИБКА ──────────────────────────────────────────────
console.log('\n═══ НЕТ ДОКУМЕНТА ═══\n');
{
  const cart = [
    { name: 'Хлеб', price: 250, qty: 1 },
    { name: 'Молоко', price: 480, qty: 1 },
    { name: 'Сигареты', marking: 'tobacco', price: 1200, qty: 1 },
    { name: 'Пиво', marking: 'beer', price: 450, qty: 2 },
  ];
  const r = ageAnswer(cart, false);

  ok(r.cart.length === 2,
     '★ Убраны ТОЛЬКО возрастные: хлеб и молоко остались');
  ok(r.cart.every((l) => !l.marking), 'Ни одной возрастной позиции');
  ok(/Убрано из чека: 2 позиции/.test(r.said),
     `★ Сказано что убрано: «${r.said}»`);
  ok(/Остальное можно пробить/.test(r.said),
     '★ И что делать дальше: покупателя не гоняем из очереди целиком');

  const да = ageAnswer(cart, true);
  ok(да.ok && да.cart.length === 4, 'Документ показали — чек цел');
}

// ── ВИД ДОХОДИТ ДО СТРОКИ ЧЕКА ─────────────────────────────────────
{
  /* Найдено живьём: строка теряла marking, и возраст не спрашивался —
     пиво уходило без вопроса о документе. */
  const cart = [];
  let n = 0;
  addToCart(cart, { id: 'g1', name: 'Пиво', price: 450, marking: 'beer' },
    1, () => 'l' + (++n));

  ok(cart[0].marking === 'beer',
     '★ Вид маркировки дошёл до строки чека — иначе возраст не спросят');
  ok(ageCheck(cart).need, 'И проверка на нём срабатывает');
}

// ── ПРАВИЛА ────────────────────────────────────────────────────────
{
  ok(Object.keys(AGE_RULES).length >= 3, `Правил: ${Object.keys(AGE_RULES).length}`);
  ok(Object.values(AGE_RULES).every((r) => r.years >= 18 && /[а-яё]/i.test(r.what)),
     '★ У каждого правила возраст и название по-русски');
}

console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
process.exit(failed ? 1 : 0);
