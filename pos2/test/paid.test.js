/*
 * ПРОВЕРКА ЭКРАНА ПОСЛЕ ОПЛАТЫ.
 *
 * Главное: сдача крупнее всего, прописью верно, «оплата прошла, а чек
 * не вышел» названо прямо.
 */
const { HOLD_MS, moneyInWords, paidView, displayView } = require('../renderer/paid.js');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };

console.log('═══ ЭТАП 17 · ПОСЛЕ ОПЛАТЫ ═══\n');

// ── СУММА ПРОПИСЬЮ ─────────────────────────────────────────────────
{
  const случаи = [
    [0, 'ноль тенге'],
    [1, 'один тенге'],
    [2, 'два тенге'],
    [5, 'пять тенге'],
    [11, 'одиннадцать тенге'],
    [21, 'двадцать один тенге'],
    [100, 'сто тенге'],
    [380, 'триста восемьдесят тенге'],
    [1000, 'одна тысяча тенге'],
    [2000, 'две тысячи тенге'],
    [5000, 'пять тысяч тенге'],
    [11000, 'одиннадцать тысяч тенге'],
    [21500, 'двадцать одна тысяча пятьсот тенге'],
    [1000000, 'один миллион тенге'],
  ];
  let плохо = 0;
  for (const [n, ждём] of случаи) {
    const r = moneyInWords(n);
    if (r !== ждём) { плохо += 1; console.log(`    ${n} → «${r}», ждали «${ждём}»`); }
  }
  ok(плохо === 0, `★ Прописью верно на ${случаи.length} случаях`);
  ok(moneyInWords(380) === 'триста восемьдесят тенге',
     `★ Сдача 380 → «${moneyInWords(380)}»: кассир называет вслух`);
  ok(moneyInWords(2000).includes('две тысячи'),
     '★ Женский род у тысяч: «две тысячи», а не «два тысячи»');
}

// ── СДАЧА — ГЛАВНОЕ НА ЭКРАНЕ ──────────────────────────────────────
{
  const чек = { number: 57, total: 1620, change: 380, items: [{}, {}, {}] };
  const v = paidView(чек);

  ok(v.hero === 'change' && v.heroLabel === 'Сдача',
     '★ Сдача — САМОЕ КРУПНОЕ: её называют вслух');
  ok(v.heroAmount === 380, 'И это сумма сдачи, а не чека');
  ok(v.heroWords === 'триста восемьдесят тенге',
     '★ Рядом прописью: в шумном магазине слышно вернее цифры');
  ok(v.number === 57 && v.positions === 3, 'Номер и число позиций на месте');
}

// ── БЕЗ СДАЧИ ──────────────────────────────────────────────────────
{
  const v = paidView({ number: 58, total: 1620, change: 0, items: [{}] });
  ok(v.hero === 'total' && v.heroLabel === 'Оплачено',
     '★ Сдачи нет — главным стал итог: кассир убеждается, что чек закрыт');
  ok(v.heroAmount === 1620, 'И это сумма чека');
  ok(v.heroWords === null, 'Прописью не нужно: сумму вслух не называют');
}

// ── ЧЕК НЕ ВЫШЕЛ, А ОПЛАТА ПРОШЛА ──────────────────────────────────
{
  const v = paidView({ number: 59, total: 1000, change: 0, items: [{}] },
    { printFailed: true });

  ok(v.printFailed, 'Беда с печатью помечена');
  ok(/ОПЛАТА ПРОШЛА/.test(v.printNote),
     '★ Сказано ГЛАВНОЕ: оплата прошла');
  ok(/Не пробивайте заново/.test(v.printNote),
     '★ И самое опасное отбито: иначе покупатель заплатит ДВАЖДЫ');
  ok(/Повторить печать/.test(v.printNote), 'И сказано, что делать');
}

// ── СКОЛЬКО ДЕРЖИМ ─────────────────────────────────────────────────
{
  ok(HOLD_MS === 8000, '★ Восемь секунд: прочитать успевают, очередь ждёт немного');
  ok(paidView({ number: 1, total: 100, change: 0, items: [] }).holdMs === 8000,
     'И экран это знает');
}

// ── ДИСПЛЕЙ ПОКУПАТЕЛЯ ─────────────────────────────────────────────
console.log('\n═══ ДИСПЛЕЙ ПОКУПАТЕЛЯ ═══\n');
{
  const пусто = displayView({ cart: [], due: 0 });
  ok(пусто.mode === 'idle', 'Касса свободна — дисплей спокоен');

  const cart = [
    { name: 'Молоко 2,5%', qty: 2, price: 480, discount: 0 },
    { name: 'Хлеб', qty: 1, price: 250, discount: 0 },
  ];
  const продажа = displayView({ cart, due: 1210 });
  ok(продажа.mode === 'sale', 'Идёт продажа');
  ok(продажа.lastName === 'Хлеб' && продажа.lastSum === 250,
     '★ Виден ПОСЛЕДНИЙ пробитый товар: покупатель следит за кассиром');
  ok(продажа.total === 1210 && продажа.positions === 2,
     'И общий итог с числом позиций');

  const оплачено = displayView({ receipt: { total: 1620, change: 380 } });
  ok(оплачено.mode === 'paid' && оплачено.change === 380,
     '★ После оплаты — сдача: покупатель видит её сам');
  ok(оплачено.words === 'триста восемьдесят тенге',
     'И прописью: не переспорить при недоверии');
}

console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
process.exit(failed ? 1 : 0);
