/*
 * ПРОВЕРКА СКАНЕРА.
 *
 * Главное: отличить сканер от человека, разобрать штрихкод весов,
 * сказать словами, если товара нет.
 */
const { makeScanner, parseWeighted, resolveScan, SCAN_MS } = require('../renderer/scan.js');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };

const каталог = [
  { id: '1', name: 'Хлеб', price: 250, barcodes: ['4870001234567'] },
  { id: '2', name: 'Яблоки', price: 890, plu: '123', unit: 'кг' },
  { id: '3', name: 'Сыр', price: 4500, plu: '7', unit: 'кг' },
];

console.log('═══ ЭТАП 12 · СКАНЕР ═══\n');

// ── СКАНЕР ПРОТИВ ЧЕЛОВЕКА ─────────────────────────────────────────
{
  let поймано = null;
  const s = makeScanner({ onCode: (c) => { поймано = c; } });

  // Сканер: знаки за миллисекунды, потом Enter
  let t = 1000;
  for (const k of '4870001234567') { s.key({ key: k }, t); t += 5; }
  const съел = s.key({ key: 'Enter' }, t);

  ok(поймано === '4870001234567', `★ Сканер прочитан целиком: ${поймано}`);
  ok(съел === true, '★ Enter от сканера съеден: он не «нажал кнопку» на экране');
}

// ── ЧЕЛОВЕК НАБИРАЕТ МЕДЛЕННО ──────────────────────────────────────
{
  let поймано = null;
  const s = makeScanner({ onCode: (c) => { поймано = c; } });

  // Кассир печатает: паузы по 300 мс
  let t = 1000;
  for (const k of '12') { s.key({ key: k }, t); t += 300; }
  s.key({ key: 'Enter' }, t);

  ok(поймано === null,
     '★ Два знака от человека — НЕ штрихкод: касса не пойдёт искать товар «12»');
}

// ── ЧЕЛОВЕК ПЕРЕДУМАЛ И ВЗЯЛ СКАНЕР ────────────────────────────────
{
  let поймано = null;
  const s = makeScanner({ onCode: (c) => { поймано = c; } });

  let t = 1000;
  // Начал печатать руками
  for (const k of '99') { s.key({ key: k }, t); t += 400; }
  // Потом взял сканер — пауза, дальше быстро
  t += 500;
  for (const k of '4870001234567') { s.key({ key: k }, t); t += 5; }
  s.key({ key: 'Enter' }, t);

  ok(поймано === '4870001234567',
     '★ Начатое руками не приклеилось к штрихкоду: пауза всё сбросила');
}

// ── ЗНАКИ ДОХОДЯТ ДО ПОЛЕЙ ─────────────────────────────────────────
{
  const s = makeScanner({ onCode: () => {} });
  const съел = s.key({ key: '5' }, 1000);
  ok(съел === false,
     '★ Знак НЕ съеден: пока нет Enter, неясно — сканер это или кассир печатает');
}

// ── ШТРИХКОД ВЕСОВ ─────────────────────────────────────────────────
console.log('\n═══ ШТРИХКОД ВЕСОВ ═══\n');
{
  // Раскладка: 2 префикс + 5 товар + 5 вес в граммах + 1 контроль.
  const r = parseWeighted('2200123045000');
  ok(r && r.plu === '123' && r.qty === 4.5,
     `★ Разобран: товар ${r && r.plu}, вес ${r && r.qty} кг`);

  ok(parseWeighted('2200123004500').qty === 0.45,
     '★ 450 граммов — это 0,45 кг: обычная покупка сыра');
  ok(parseWeighted('2100007123450').plu === '7', 'Ведущие нули в коде убраны');

  ok(parseWeighted('2200123000000') === null,
     '★ Ноль граммов — НЕ берём: весы не взвесили, товар ушёл бы даром');
  ok(parseWeighted('4870001234567') === null, 'Обычный штрихкод не считаем весовым');
  ok(parseWeighted('123') === null && parseWeighted('') === null, 'Мусор отброшен');

  // Префикс настраивается: у магазинов он разный
  ok(parseWeighted('2300123004500') === null, 'Префикс 23 по умолчанию не наш');
  ok(parseWeighted('2300123004500', { prefixes: ['23'] }) !== null,
     '★ Префикс настраивается: у одних магазинов 22, у других 23');
}

// ── ЧТО ДЕЛАТЬ С ОТСКАНИРОВАННЫМ ───────────────────────────────────
console.log('\n═══ РАЗБОР СКАНА ═══\n');
{
  const r1 = resolveScan('4870001234567', каталог);
  ok(r1.ok && r1.good.name === 'Хлеб' && r1.qty === 1,
     '★ Обычный товар: Хлеб, одна штука');

  const r2 = resolveScan('2200123045000', каталог);
  ok(r2.ok && r2.good.name === 'Яблоки' && r2.qty === 4.5,
     '★ Весовой: Яблоки, 4,5 кг — кассир не вводил НИЧЕГО');
  ok(r2.from === 'весы', 'И помечено, откуда взялось');

  const r3 = resolveScan('9999999999999', каталог);
  ok(!r3.ok && /не найден/.test(r3.said), 'Не нашли — сказали');
  ok(/9999999999999/.test(r3.said),
     '★ И код назван целиком: кассир продиктует его владельцу');
  ok(/заведёт товар в кабинете/.test(r3.said),
     'И кому звонить: кассир сам завести товар не может');

  const r4 = resolveScan('2209990045000', каталог);
  ok(!r4.ok && /Весовой товар с кодом 999/.test(r4.said),
     '★ Весовой не найден — сказано, что он весовой и какой код');

  ok(!resolveScan('', каталог).ok, 'Пустой скан отбит');
}

console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
process.exit(failed ? 1 : 0);
