/*
 * ПРОВЕРКА КАТАЛОГА.
 *
 * На настоящих названиях, какие бывают в магазине.
 */
const { QUICK_TAB, searchGoods, catTabs, pickGoods, findByBarcode } = require('../renderer/goods.js');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };

const товары = [
  { id: '1', name: 'Хлеб «Тандыр»', price: 250, category: 'Хлеб', quick: true, barcodes: ['4870001'] },
  { id: '2', name: 'Отруби хлебные', price: 480, category: 'Бакалея', barcodes: ['4870002'] },
  { id: '3', name: 'Молоко Айналайын 2.5%', price: 420, category: 'Молочное', quick: true, barcodes: ['4870003'] },
  { id: '4', name: 'Молоко Простоквашино 3.2%', price: 560, category: 'Молочное', barcodes: ['4870004'] },
  { id: '5', name: 'Сигареты Winston', price: 800, category: 'Табак', marked: true, barcodes: ['4870005'] },
  { id: '6', name: 'Вода «Тассай» 1л', price: 200, category: 'Напитки', quick: true, barcodes: ['4870006', '4870066'] },
];

console.log('═══ ЭТАП 11 · КАТАЛОГ ═══\n');

// ── ПОИСК С НАЧАЛА ВЫШЕ ────────────────────────────────────────────
{
  const r = searchGoods(товары, 'хле');
  ok(r.length === 2, 'Нашлись оба: «Хлеб» и «Отруби хлебные»');
  ok(r[0].name.startsWith('Хлеб'),
     `★ С начала — ВЫШЕ: первым «${r[0].name}», кассир жмёт его не глядя`);
}

// ── СЛОВА ПО ОТДЕЛЬНОСТИ ───────────────────────────────────────────
{
  const r = searchGoods(товары, 'молоко 2.5');
  ok(r.length === 1 && r[0].id === '3',
     '★ «молоко 2.5» нашло «Молоко Айналайын 2.5%» — у донора не нашло бы');

  const r2 = searchGoods(товары, '2.5 молоко');
  ok(r2.length === 1 && r2[0].id === '3', 'И в обратном порядке слов тоже');

  const r3 = searchGoods(товары, 'вода тассай');
  ok(r3.length === 1, 'Два слова из названия — нашли');
}

// ── ПОИСК ПО ШТРИХКОДУ РУКАМИ ──────────────────────────────────────
{
  const r = searchGoods(товары, '4870005');
  ok(r.length === 1 && r[0].name.includes('Winston'),
     '★ Набрал код с коробки — нашли: сканер мог не взять мятый код');
}

// ── ПОИСК НИЧЕГО НЕ НАШЁЛ ──────────────────────────────────────────
{
  ok(searchGoods(товары, 'квашеная капуста').length === 0,
     'Нет товара — пустой список, а не весь каталог');
  ok(searchGoods(товары, '').length === товары.length,
     'Пустой запрос — весь каталог');
  ok(searchGoods(товары, '   ').length === товары.length,
     'Пробелы — тоже весь: кассир задел клавишу');
}

// ── ВКЛАДКИ ────────────────────────────────────────────────────────
{
  const tabs = catTabs(товары);
  ok(tabs[0] === QUICK_TAB, '★ «Ходовое» первой: там девять из десяти продаж');
  ok(tabs.includes('Молочное') && tabs.includes('Табак'), 'Категории на месте');
  ok(tabs.length === 6, `Вкладок ${tabs.length}: ${tabs.join(', ')}`);

  // Пустых вкладок не делаем
  const без = catTabs([{ id: 'x', name: 'Товар' }]);
  ok(без.length === 1 && без[0] === 'Все',
     '★ Категорий нет — одна вкладка «Все», а не пустой ряд');

  const безХодовых = catTabs(товары.map((g) => ({ ...g, quick: false })));
  ok(!безХодовых.includes(QUICK_TAB),
     '★ Ходовых нет — вкладки нет: нажатие в никуда сбивает кассира');
}

// ── ОТБОР ПО ВКЛАДКЕ ───────────────────────────────────────────────
{
  ok(pickGoods(товары, { tab: QUICK_TAB }).length === 3, 'Ходовое: три товара');
  ok(pickGoods(товары, { tab: 'Молочное' }).length === 2, 'Молочное: два');
  ok(pickGoods(товары, { tab: 'Все' }).length === 6, '«Все» — весь каталог');
}

// ── ПОИСК СИЛЬНЕЕ ВКЛАДКИ ──────────────────────────────────────────
{
  // Стоим на «Табак», ищем «молоко» — должно найтись
  const r = pickGoods(товары, { tab: 'Табак', query: 'молоко' });
  ok(r.length === 2,
     '★ ПОИСК СКВОЗНОЙ: стоим на «Табак», а «молоко» нашлось — их правило');
  ok(r.every((g) => g.category === 'Молочное'),
     'И нашлось именно молоко, а не табак');
}

// ── ШТРИХКОД: ТОЧНОЕ СОВПАДЕНИЕ ────────────────────────────────────
{
  ok(findByBarcode(товары, '4870003').id === '3', 'Сканер нашёл товар');
  ok(findByBarcode(товары, '4870066').id === '6',
     '★ Второй штрихкод того же товара тоже работает');
  ok(findByBarcode(товары, '48700') === null,
     '★ ЧАСТЬ кода не годится: продали бы не тот товар');
  ok(findByBarcode(товары, '') === null && findByBarcode(товары, null) === null,
     'Пустой код — ничего');
}

// ── БОЛЬШОЙ КАТАЛОГ НЕ ТОРМОЗИТ ────────────────────────────────────
{
  const много = [];
  for (let i = 0; i < 20000; i += 1) {
    много.push({ id: String(i), name: `Товар ${i}`, category: 'Разное',
      barcodes: [String(4870000000 + i)] });
  }
  const t = Date.now();
  const r = searchGoods(много, 'товар 1999');
  const ms = Date.now() - t;
  ok(r.length > 0 && ms < 500,
     `★ Двадцать тысяч товаров: поиск за ${ms} мс — касса не встанет`);

  const t2 = Date.now();
  findByBarcode(много, '4870019999');
  ok(Date.now() - t2 < 100, 'Сканер находит мгновенно: покупатель не ждёт');
}

console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
process.exit(failed ? 1 : 0);
