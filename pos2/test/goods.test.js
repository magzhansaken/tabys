/*
 * ПРОВЕРКА КАТАЛОГА.
 *
 * Главное: поиск сквозной, порядок выдачи полезный, пусто объяснено.
 */
const { QUICK, catTabs, searchGoods, visibleGoods, emptyText, findByBarcode,
  matchGood } = require('../renderer/goods.js');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };

/* Каталог как в настоящем магазине. */
const каталог = [
  { id: '1', name: 'Хлеб «Тандыр»', price: 250, category: 'Хлеб', quick: true, barcodes: ['4870001'] },
  { id: '2', name: 'Молоко 2,5%', price: 480, category: 'Молочное', quick: true, barcodes: ['4870002'] },
  { id: '3', name: 'Сгущённое молоко', price: 690, category: 'Молочное', barcodes: ['4870003'] },
  { id: '4', name: 'Сигареты Winston', price: 1200, category: 'Табак', marked: true, barcodes: ['4870004'] },
  { id: '5', name: 'Пакет-майка', price: 30, category: 'Прочее', quick: true, barcodes: ['4870005'] },
  { id: '6', name: 'Молочный шоколад', price: 550, category: 'Сладкое', barcodes: ['4870006'] },
];

console.log('═══ ЭТАП 11 · КАТАЛОГ ═══\n');

// ── ВКЛАДКИ ────────────────────────────────────────────────────────
{
  const t = catTabs(каталог);
  ok(t[0] === QUICK, '★ «Ходовое» ПЕРВЫМ: восемь чеков из десяти — это оно');
  ok(t.includes('Хлеб') && t.includes('Табак'), 'Категории на месте');

  const дальше = t.slice(1);
  ok(дальше.join() === [...дальше].sort((a, b) => a.localeCompare(b, 'ru')).join(),
     '★ Дальше по алфавиту: кассир целится не глядя, привыкнув к месту');

  const без = catTabs(каталог.map((g) => ({ ...g, quick: false })));
  ok(без[0] !== QUICK, 'Ходовых нет — вкладки нет: пустая вкладка обманывает');

  ok(catTabs([])[0] === 'Все', '★ Каталог пуст — одна вкладка «Все», а не пустой ряд');
}

// ── ПОИСК СКВОЗНОЙ ─────────────────────────────────────────────────
{
  const r = searchGoods(каталог, 'молок');
  ok(r.length === 2, `★ Поиск идёт по ВСЕМУ каталогу, мимо вкладок: нашёл ${r.length}`);
  ok(r.every((g) => /молок/i.test(g.name)),
     'И нашёл ровно то, что просили — «Молочный шоколад» тут ни при чём');
  ok(r[0].name === 'Молоко 2,5%',
     `★ Начинающееся с запроса — ПЕРВЫМ: «${r[0].name}»`);

  const серединой = searchGoods(каталог, 'локо');
  ok(серединой.length >= 2, '★ Ищем и по СЕРЕДИНЕ слова: кассир печатает быстро');
}

// ── ПОИСК ПО ШТРИХКОДУ ─────────────────────────────────────────────
{
  const r = searchGoods(каталог, '4870004');
  ok(r.length === 1 && r[0].name === 'Сигареты Winston',
     '★ Ищем и по штрихкоду: покупатель принёс товар без наклейки');
  const часть = searchGoods(каталог, '48700');
  ok(часть.length === 6, 'И по части кода: кассир читает цифры с упаковки');
}

// ── ХОДОВОЕ ВПЕРЁД ПРИ РАВЕНСТВЕ ───────────────────────────────────
{
  // «Молочный шоколад» и «Сгущённое молоко» — оба не начинаются с «молок»
  const r = searchGoods(каталог, 'молоч');
  ok(r[0].name === 'Молочный шоколад', 'Начинающееся всё равно первое');
}

// ── ЧТО ВИДНО СЕЙЧАС ───────────────────────────────────────────────
{
  ok(visibleGoods(каталог, { tab: QUICK }).length === 3, 'Вкладка «Ходовое» — три товара');
  ok(visibleGoods(каталог, { tab: 'Табак' }).length === 1, 'Вкладка «Табак» — один');
  ok(visibleGoods(каталог, { tab: 'Табак', query: 'молок' }).length === 2,
     '★ Стоим во вкладке «Табак», а находим молоко: поиск сквозной');
  ok(visibleGoods(каталог, { tab: null }).length === 6, 'Без вкладки — весь каталог');
}

// ── ПУСТО ОБЪЯСНЕНО ────────────────────────────────────────────────
{
  ok(/Позовите владельца/.test(emptyText({ catalog: [], tab: QUICK })),
     '★ Каталога нет вовсе — сказано, что делать');
  ok(/Проверьте написание/.test(emptyText({ catalog: каталог, query: 'квадрокоптер' })),
     '★ Не нашлось — сказано, как быть, а не пустое место');
  ok(/отсканируйте штрихкод/.test(emptyText({ catalog: каталог, query: 'ххх' })),
     'И подсказан второй путь: сканер');
  ok(/Владелец отмечает их в кабинете/.test(
      emptyText({ catalog: каталог.map((g) => ({ ...g, quick: false })), tab: QUICK })),
     '★ Ходовых нет — объяснено, кто их отмечает');
  ok(/во вкладке «Табак» пока нет/i.test(emptyText({ catalog: каталог, tab: 'Табак' })),
     'Пустая вкладка названа');
}

// ── СКАНЕР: ТОЧНОЕ СОВПАДЕНИЕ ──────────────────────────────────────
{
  ok(findByBarcode(каталог, '4870002').name === 'Молоко 2,5%', 'Сканер находит товар');
  ok(findByBarcode(каталог, '48700') === null,
     '★ Сканеру нужно ТОЧНОЕ совпадение: часть кода — не тот товар');
  ok(findByBarcode(каталог, '') === null && findByBarcode(каталог, null) === null,
     'Пустой код ничего не находит');
  ok(findByBarcode(каталог, ' 4870002 ').name === 'Молоко 2,5%',
     'Пробелы от сканера убраны');
}

// ── СРАВНЕНИЕ ──────────────────────────────────────────────────────
{
  ok(matchGood(каталог[0], ''), 'Пустой запрос подходит всем');
  ok(matchGood(каталог[0], 'ТАНДЫР'), '★ Регистр не мешает: кассир печатает как придётся');
}

console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
process.exit(failed ? 1 : 0);
