/*
 * ПРОВЕРКА СТРАНИЦЫ ЦЕЛИКОМ.
 *
 * Все файлы кассы грузятся на ОДНУ страницу, в одну область имён.
 * Проверки читают их порознь и такого не видят.
 *
 * ЭТА ПРОВЕРКА РОДИЛАСЬ ИЗ БЕДЫ: RU и KZ были объявлены и в языках, и
 * в клавиатуре. Второе объявление ломало ВЕСЬ файл клавиатуры — на
 * кассе её просто не было, а проверки молчали.
 */
const fs = require('fs');
const path = require('path');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };

const дом = path.join(__dirname, '..', 'renderer');
const html = fs.readFileSync(path.join(дом, 'index.html'), 'utf8');

console.log('═══ СТРАНИЦА КАССЫ ═══\n');

// ── ВСЕ ФАЙЛЫ ПОДКЛЮЧЕНЫ ───────────────────────────────────────────
{
  const наДиске = fs.readdirSync(дом).filter((f) => f.endsWith('.js'));
  const вСтранице = [...html.matchAll(/src="([^"]+\.js)"/g)].map((m) => m[1]);

  const забытые = наДиске.filter((f) => !вСтранице.includes(f));
  ok(забытые.length === 0,
     забытые.length ? `✘ НЕ подключены: ${забытые.join(', ')}`
       : `★ Все ${наДиске.length} файлов подключены к странице`);

  const лишние = вСтранице.filter((f) => !наДиске.includes(f));
  ok(лишние.length === 0,
     лишние.length ? `✘ Подключены, но их нет: ${лишние.join(', ')}`
       : 'И ни одного лишнего');

  const задвоены = вСтранице.filter((f, i) => вСтранице.indexOf(f) !== i);
  ok(задвоены.length === 0,
     задвоены.length ? `✘ Задвоены: ${задвоены.join(', ')}` : 'И ни одного дважды');
}

// ── ИМЕНА НЕ СТАЛКИВАЮТСЯ ──────────────────────────────────────────
{
  /* Ищем объявления верхнего уровня в каждом файле и сверяем: два
     файла с одним именем — и второй сломается целиком. */
  const где = new Map();

  for (const f of fs.readdirSync(дом).filter((x) => x.endsWith('.js'))) {
    const src = fs.readFileSync(path.join(дом, f), 'utf8');
    /* СЛОВО ЦЕЛИКОМ, а не по первой букве: \w не знает кириллицы, и
       «ДЕСЯТЬ» с «ДЕСЯТКИ» слились бы в «Д». */
    for (const m of src.matchAll(/^(?:const|let|function|class)\s+([A-Za-zА-Яа-яЁё_$][A-Za-zА-Яа-яЁё0-9_$]*)/gm)) {
      const имя = m[1];
      if (!где.has(имя)) где.set(имя, []);
      где.get(имя).push(f);
    }
  }

  const столкновения = [...где.entries()].filter(([, files]) => files.length > 1);

  ok(столкновения.length === 0,
     столкновения.length
       ? `✘ Имена столкнулись: ${столкновения.map(([n, f]) => `${n} (${f.join(', ')})`).join('; ')}`
       : `★ Ни одного столкновения имён среди ${где.size} объявлений`);
}

// ── ПОРЯДОК: ЯДРО ПОСЛЕДНИМ ────────────────────────────────────────
{
  const вСтранице = [...html.matchAll(/src="([^"]+\.js)"/g)].map((m) => m[1]);
  ok(вСтранице[вСтранице.length - 1] === 'app.js',
     '★ Связка подключена ПОСЛЕДНЕЙ: она зовёт и ядро, и все свёртки');
  ok(вСтранице.indexOf('core.js') < вСтранице.indexOf('app.js'),
     'И ядро раньше неё');
}

// ── КАЖДЫЙ ФАЙЛ ЧИТАЕТСЯ ───────────────────────────────────────────
{
  const битые = [];
  for (const f of fs.readdirSync(дом).filter((x) => x.endsWith('.js'))) {
    try { new Function(fs.readFileSync(path.join(дом, f), 'utf8')); }
    catch (e) { битые.push(`${f}: ${e.message}`); }
  }
  ok(битые.length === 0,
     битые.length ? `✘ Не читаются: ${битые.join('; ')}` : '★ Все файлы читаются без ошибок');
}

console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
process.exit(failed ? 1 : 0);
