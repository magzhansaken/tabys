/*
 * ПРОВЕРКА ПЕЧАТИ.
 *
 * Главное: очередь не рвёт ленту, PDF назван, чек ровный на обеих
 * ширинах.
 */
const { receiptLines, refundLines, money } = require('../renderer/receipt.js');
const { encodeText, build, pair } = require('../electron/escpos.cjs');
const { isVirtual } = require('../electron/printer.cjs');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };

const чек = {
  number: 57, at: new Date('2026-08-21T14:32:00').toISOString(),
  store: 'Мини-маркет', register: 'Касса 1', cashier: 'Айгуль',
  items: [
    { name: 'Молоко 2,5%', qty: 2, price: 480, marks: [] },
    { name: 'Яблоки', qty: 0.45, price: 890, unit: 'кг', marks: [] },
    { name: 'Сигареты', qty: 1, price: 1200, discount: 100, marks: ['МАРКА-1'] },
  ],
  discount: 200, total: 2411, cash: 3000, change: 589,
};

console.log('═══ ЭТАП 18 · ПЕЧАТЬ ═══\n');

(async () => {

// ── ОЧЕРЕДЬ НЕ РВЁТ ЛЕНТУ ──────────────────────────────────────────
{
  let chain = Promise.resolve();
  const enqueue = (t) => (chain = chain.then(t, t));
  const след = [];
  const job = (n, ms) => () => new Promise((r) => {
    след.push('начал ' + n);
    setTimeout(() => { след.push('кончил ' + n); r(); }, ms);
  });

  enqueue(job('чек', 30));
  enqueue(job('повтор', 10));
  enqueue(job('ящик', 5));
  await chain;

  let смешалось = false, открыт = false;
  for (const s of след) {
    if (s.startsWith('начал')) { if (открыт) смешалось = true; открыт = true; }
    else открыт = false;
  }
  ok(!смешалось, '★ Три задания разом — строго по одному, лента цела');
  ok(след.length === 6, 'И все три дошли до конца');
}

// ── PDF НАЗВАН ─────────────────────────────────────────────────────
{
  const плохие = ['Microsoft Print to PDF', 'Microsoft XPS Document Writer',
    'OneNote (Desktop)', 'Факс', 'Fax', 'Отправить в OneNote 16'];
  const хорошие = ['XP-80C', 'EPSON TM-T20', 'Star TSP100', 'Rongta RP58'];

  ok(плохие.every(isVirtual), '★ Все виртуальные принтеры названы');
  ok(хорошие.every((p) => !isVirtual(p)), '★ А настоящие проходят');
  ok(!isVirtual(''), 'Пустое имя не считаем виртуальным');
}

// ── ЗНАКИ НА ЛЕНТЕ ─────────────────────────────────────────────────
{
  const назад = (b) => b.map((x) => {
    if (x < 128) return String.fromCharCode(x);
    if (x >= 0x80 && x <= 0x9f) return 'АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ'[x - 0x80];
    if (x >= 0xa0 && x <= 0xaf) return 'абвгдежзийклмноп'[x - 0xa0];
    if (x >= 0xe0 && x <= 0xef) return 'рстуфхцчшщъыьэюя'[x - 0xe0];
    return '?';
  }).join('');

  ok(назад(encodeText('960 ₸')) === '960 тг',
     '★ Знак тенге заменён на «тг»: принтер его не знает, вышел бы «?»');
  ok(назад(encodeText('Хлеб')) === 'Хлеб', 'Русские буквы целы');
  ok(назад(encodeText('«Тандыр»')) === '"Тандыр"', 'Ёлочки заменены: на ленте выходят криво');
  ok(назад(encodeText('Сүт')) === 'Сут', '★ Казахские буквы заменены на близкие, а не на мусор');
  ok(назад(encodeText('А — Б')) === 'А - Б', 'Длинное тире заменено');
}

// ── КОМАНДЫ ПРИНТЕРА ───────────────────────────────────────────────
{
  const b = build(['Проба'], { width: 32, cut: true });
  ok(b[0] === 0x1b && b[1] === 0x40, '★ Лента начинается со сброса: принтер мог остаться в жирном');
  ok(b.includes(0x11), 'Кодировка задана');

  const без = build(['Проба'], { width: 32, cut: false });
  ok(b.length > без.length, 'Отрез добавляет команду');

  const две = build(['Проба'], { width: 32, copies: 2 });
  const одна = build(['Проба'], { width: 32, copies: 1 });
  ok(две.length === одна.length * 2, '★ Две копии — повтор всей ленты');

  const сЯщиком = build(['Проба'], { width: 32, openDrawer: true });
  ok(сЯщиком.length > одна.length, 'Ящик открывается командой принтера');
}

// ── ЧЕК РОВНЫЙ НА ОБЕИХ ШИРИНАХ ────────────────────────────────────
console.log('\n═══ ЛЕНТА ЧЕКА ═══\n');
{
  for (const width of [48, 32]) {
    const lines = receiptLines(чек, { width });
    const длинные = lines.filter((l) => {
      const t = typeof l === 'string' ? l : (l.text || '');
      return t.length > width;
    });
    ok(длинные.length === 0,
       `★ На ленте ${width} знаков ничего не вылезает за край`);
  }
}

// ── ЧТО В ЧЕКЕ ─────────────────────────────────────────────────────
{
  const текст = receiptLines(чек, { width: 48 })
    .map((l) => (typeof l === 'string' ? l : l.text)).join('\n');

  ok(/Чек №57/.test(текст), 'Номер чека');
  ok(/Кассир: Айгуль/.test(текст), 'Кассир назван: покупатель знает, к кому обращаться');
  ok(/Мини-маркет/.test(текст), 'Магазин');
  ok(/Молоко 2,5%/.test(текст) && /Яблоки/.test(текст), 'Товары');
  ok(/0,45 кг x 890/.test(текст),
     '★ Весовой товар: вес через ЗАПЯТУЮ — по-русски дробное пишется так');
  ok(/марка …МАРКА-1/.test(текст),
     '★ Марка на чеке: покупатель может проверить подлинность товара');
  ok(/Скидка на чек/.test(текст) && /-200/.test(текст), 'Скидка видна');
  ok(/ИТОГО/.test(текст) && /2 411/.test(текст), 'Итог');
  ok(/Сдача/.test(текст) && /589/.test(текст), 'Сдача');
  ok(/Спасибо за покупку/.test(текст), 'Подвал');

  const возврат = receiptLines({ ...чек, isRefund: true,
    returnNote: 'Возврат принят. Обмен и возврат — по чеку в течение 14 дней' },
    { width: 40 });
  const тВозврат = возврат.map((l) => (typeof l === 'string' ? l : l.text)).join('\n');
  ok(!/Спасибо за покупку/.test(тВозврат) && /Деньги возвращены/.test(тВозврат),
     '★ На возврате НЕ благодарят за покупку: деньги вернули за брак');
  ok(возврат.every((l) => (typeof l === 'string' ? l : l.text || '').length <= 40),
     '★ Длинная подпись перенесена по словам: не вылезает за ленту');
}

// ── ИМЯ ТОВАРА НЕ ОБРЕЗАЕТСЯ ───────────────────────────────────────
{
  const длинный = { ...чек, items: [{
    name: 'Колбаса варёная «Докторская» высший сорт охлаждённая',
    qty: 1, price: 2500, marks: [] }] };
  const lines = receiptLines(длинный, { width: 32 })
    .map((l) => (typeof l === 'string' ? l : l.text));

  ok(lines.some((l) => /Колбаса варёная/.test(l)),
     '★ Имя товара отдельной строкой: обрезать нельзя, покупатель не поймёт, за что платит');
}

// ── ВОЗВРАТ ОТЛИЧАЕТСЯ ─────────────────────────────────────────────
{
  const r = refundLines(чек, { width: 48 });
  const первая = typeof r[0] === 'string' ? r[0] : r[0].text;
  ok(/ВОЗВРАТ/.test(первая) && r[0].big,
     '★ Возврат виден с первого взгляда: его нельзя спутать с продажей');
}

// ── ДЕНЬГИ ─────────────────────────────────────────────────────────
{
  /* ЗНАЧКА ВАЛЮТЫ В ТЕЛЕ ЧЕКА НЕТ — правило донора: он шире одного
     байта в кодировке принтера и ломал раскладку. Валюта названа один
     раз, под итогом. */
  ok(money(1234567) === '1 234 567', 'Разряды разделены: «1 234 567», а не «1234567»');
  ok(!money(1234567).includes('₸'),
     '★ И без значка: он ломал раскладку на узкой ленте');
  ok(money(0) === '0', 'Ноль');
  ok(money(400.5) === '401', 'Дробное округлено: копеек в кассе нет');
}

console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
process.exit(failed ? 1 : 0);
})();
