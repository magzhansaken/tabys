/*
 * ПРОВЕРКА ПЕЧАТИ.
 *
 * Главное: лента ровная, очередь по одному, печать в PDF названа.
 */
const { receiptLines, paperWidth, padLR, center, num } = require('../renderer/receipt.js');
const { isVirtual, encode, enqueue } = require('../electron/printer.cjs');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };

const чек = {
  number: 57, at: '2026-08-21T14:20:00', store: 'Мини-маркет на Абая',
  register: 'Касса 1', cashier: 'Айгуль',
  items: [
    { name: 'Молоко 2,5%', qty: 2, price: 480, discount: 0 },
    { name: 'Хлеб «Тандыр» бездрожжевой с семенами', qty: 1, price: 250, discount: 0 },
    { name: 'Яблоки', qty: 0.45, price: 890, discount: 0 },
    { name: 'Сыр', qty: 1, price: 4270, discount: 200 },
  ],
  discount: 100, total: 5981, cash: 6000, card: 0, change: 19,
};

console.log('═══ ЭТАП 18 · ПЕЧАТЬ ═══\n');

// ── ЛЕНТА РОВНАЯ ───────────────────────────────────────────────────
{
  for (const w of [32, 48]) {
    const lines = receiptLines(чек, w);
    /* ПРОВЕРЯЕМ РОВНО ШИРИНУ, А НЕ «НЕ БОЛЬШЕ».
       Прежняя проверка смотрела только «не длиннее ленты» — и
       пропустила беду, из-за которой чек выходил БЕЗ ЕДИНОЙ СУММЫ:
       правая часть строк терялась, строки становились короткими, а
       проверку это устраивало. */
    // Строки с двумя колонками обязаны быть РОВНО по ширине: именно
    // там терялись суммы. Названия товаров тянуть незачем — они слева.
    const двухколонные = lines.filter((l) => /\s{2,}\S/.test(l));
    const кривые = двухколонные.filter((l) => l.length !== w);
    ok(кривые.length === 0,
       `★ Лента ${w}: все ${двухколонные.length} строк с суммами ровно по ширине`);
    ok(lines.every((l) => l.length <= w), 'И ничего не вылезло за ленту');
  }
}

// ── СУММЫ НА ЛЕНТЕ ─────────────────────────────────────────────────
{
  const lines = receiptLines(чек, 48);
  /* Числа печатаются с НЕРАЗРЫВНЫМ пробелом — так их разбивает
     разрядка. Сравниваю по цифрам, а не по виду пробела. */
  const цифры = (s) => String(s).replace(/[^\d]/g, '');
  const итог = lines.find((l) => l.startsWith('ИТОГО'));
  ok(итог && цифры(итог) === '5981',
     `★ ИТОГ НА ЛЕНТЕ: «${итог && итог.trim()}» — без этого чек был бы без сумм`);
  ok(lines.some((l) => /Сдача\s+19\s*$/.test(l)), 'И сдача');
  ok(lines.some((l) => /960\s*$/.test(l)) && lines.some((l) => /401\s*$/.test(l)),
     'И суммы каждой строки');
}

// ── ВАЛЮТА НАЗВАНА ОДИН РАЗ ────────────────────────────────────────
{
  const lines = receiptLines(чек, 48);
  const со_значком = lines.filter((l) => l.includes('₸'));
  ok(со_значком.length === 0,
     '★ Значка ₸ в теле НЕТ: он шире байта и ломал раскладку');
  ok(lines.some((l) => l.includes('ТЕНГЕ')),
     '★ Валюта названа ОДИН раз, строкой под итогом');
}

// ── ЦЕНА ВИДНА ─────────────────────────────────────────────────────
{
  const lines = receiptLines(чек, 48);
  ok(lines.some((l) => /2 × 480/.test(l)),
     '★ Количество и цена отдельной строкой: спор «почему дорого» гасится');
  ok(lines.some((l) => /0,45 × 890/.test(l)),
     'Весовой товар — с дробным количеством через запятую');
  ok(lines.some((l) => /скидка.*-200/.test(l)), 'Скидка на строку видна');
  ok(lines.some((l) => /Скидка на чек.*-100/.test(l)), 'И скидка на чек');
}

// ── ДЛИННОЕ ИМЯ ПЕРЕНОСИТСЯ ────────────────────────────────────────
{
  const lines = receiptLines(чек, 32);
  const хлеб = lines.findIndex((l) => l.startsWith('Хлеб'));
  ok(хлеб >= 0 && !lines[хлеб].endsWith('…'),
     '★ Длинное имя ПЕРЕНОСИТСЯ, а не режется: покупатель понимает, за что платил');
}

// ── МАРКИ НЕ ПЕЧАТАЮТСЯ ────────────────────────────────────────────
{
  const с_марками = { ...чек, items: [{ name: 'Водка', qty: 1, price: 3200,
    marks: ['01487000123456721ABCDEFGHIJKLMNOP'] }] };
  const lines = receiptLines(с_марками, 48);
  ok(!lines.some((l) => l.includes('ABCDEF')),
     '★ Марки НЕ на ленте: 40 знаков мусора, а ленты уходит вдвое больше');
}

// ── ЧЕК БЕЗ СВЯЗИ ──────────────────────────────────────────────────
{
  const lines = receiptLines({ ...чек, offline: true }, 48);
  ok(lines.some((l) => /уйдёт в налоговую при связи/.test(l)),
     '★ Пробит без связи — покупатель предупреждён: иначе решит, что обманули');
  ok(!receiptLines(чек, 48).some((l) => /при связи/.test(l)),
     'При связи лишнего не пишем');
}

// ── ШИРИНА ИЗ НАСТРОЕК ─────────────────────────────────────────────
{
  ok(paperWidth({ printWidth: 32 }) === 32, 'Узкая лента 58 мм');
  ok(paperWidth({ printWidth: 48 }) === 48, 'Широкая 80 мм');
  ok(paperWidth({}) === 48, '★ По умолчанию 80 мм — самый частый случай');
  ok(paperWidth({ printWidth: 'ерунда' }) === 48, 'Мусор в настройке не роняет');
}

// ── ПЕЧАТЬ В PDF НАЗВАНА ───────────────────────────────────────────
console.log('\n═══ ВИРТУАЛЬНЫЕ ПРИНТЕРЫ ═══\n');
{
  const плохие = ['Microsoft Print to PDF', 'Microsoft XPS Document Writer',
    'OneNote (Desktop)', 'Факс', 'Fax', 'Отправить в OneNote'];
  const хорошие = ['XP-80C', 'EPSON TM-T20', 'Star TSP100', 'POS-58'];

  const п = плохие.filter((n) => !isVirtual(n));
  const х = хорошие.filter((n) => isVirtual(n));

  ok(п.length === 0, '★ Все шесть виртуальных пойманы: они молча съедают чек');
  ok(х.length === 0, `★ Настоящие принтеры проходят: ${хорошие.join(', ')}`);
}

// ── ОЧЕРЕДЬ: ОДНО ЗАДАНИЕ ЗА РАЗ ───────────────────────────────────
console.log('\n═══ ОЧЕРЕДЬ ПЕЧАТИ ═══\n');
(async () => {
  const след = [];
  const job = (имя, ms) => () => new Promise((r) => {
    след.push('начал ' + имя);
    setTimeout(() => { след.push('кончил ' + имя); r(); }, ms);
  });

  enqueue(job('чек', 30));
  enqueue(job('повтор', 10));
  const последний = enqueue(job('отчёт', 20));
  await последний;

  let смешалось = false, открыт = false;
  for (const s of след) {
    if (s.startsWith('начал')) { if (открыт) смешалось = true; открыт = true; }
    else открыт = false;
  }
  ok(!смешалось, '★ Три задания разом печатаются СТРОГО по одному');
  ok(след.length === 6, 'И все три дошли до конца');

  // Ошибка одного не топит следующее
  const после = [];
  enqueue(() => Promise.reject(new Error('кончилась лента')));
  await enqueue(() => { после.push('чек вышел'); return Promise.resolve(); });
  ok(после.length === 1,
     '★ Лента кончилась на отчёте — чек покупателя всё равно вышел');

  // ── КИРИЛЛИЦА ────────────────────────────────────────────────────
  {
    const b = encode(['Хлеб']);
    ok(b.includes(0x95), '★ Кириллица в CP866: иначе на ленте вопросительные знаки');
    ok(b[0] === 0x1b && b[1] === 0x40, 'Перед чеком — сброс принтера');
    ok(b.includes(0x1d) && b.includes(0x56), 'И отрезание ленты в конце');
  }

  console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
  process.exit(failed ? 1 : 0);
})();
