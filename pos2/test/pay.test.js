/*
 * ПРОВЕРКА ОПЛАТЫ.
 *
 * Главное: купюры не бывают пустыми, сдача верна, двойной тап не даёт
 * два чека.
 */
const { WAYS, tenderOptions, change, enough, planMixed, buildReceipt,
  lastWay } = require('../renderer/pay.js');
const { addToCart, cartTotal } = require('../renderer/cart.js');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };

let ln = 0; const newId = () => `l${++ln}`;

console.log('═══ ЭТАП 16 · ОПЛАТА ═══\n');

// ── УМНЫЕ КУПЮРЫ ───────────────────────────────────────────────────
{
  const случаи = [
    [1340, [1340, 1400, 1500, 2000]],
    [890,  [890, 900, 1000, 2000]],
    [2700, [2700, 3000, 5000, 10000]],
    [150,  [150, 200, 500, 1000]],
    [24000,[24000, 30000, 40000, 50000]],
  ];
  for (const [due, ждём] of случаи) {
    const r = tenderOptions(due);
    ok(JSON.stringify(r) === JSON.stringify(ждём),
       `${due} ₸ → ${r.join(' · ')}`);
  }

  // Вот тут и ломалась прежняя касса
  ok(tenderOptions(24000).length === 4,
     '★ На 24 000 ЧЕТЫРЕ кнопки: в прошлой кассе не было НИ ОДНОЙ');
  ok(tenderOptions(99999).length === 4, 'И на 99 999 тоже');
  ok(tenderOptions(0)[0] === 0, 'Пустой чек не роняет');
  ok(tenderOptions(1340)[0] === 1340,
     '★ Точная сумма ПЕРВОЙ: «без сдачи» — самый частый случай');
}

// ── СДАЧА ──────────────────────────────────────────────────────────
console.log('\n═══ СДАЧА ═══\n');
{
  ok(change(1340, 2000) === 660, '2 000 за 1 340 → сдача 660');
  ok(change(1340, 1340) === 0, 'Точно — сдачи нет');
  ok(change(1340, 1000) === 0,
     '★ Дали меньше — сдача НОЛЬ, а не минус: касса не доплачивает');
}

// ── ХВАТАЕТ ЛИ ─────────────────────────────────────────────────────
{
  const мало = enough(5000, { cash: 3000 });
  ok(!мало.ok && мало.short === 2000,
     `★ Не хватает 2 000 — сказано СКОЛЬКО, а не «мало денег»`);

  const хватит = enough(5000, { cash: 6000 });
  ok(хватит.ok && хватит.change === 1000, 'Хватило, сдача 1 000');

  const обоими = enough(5000, { cash: 2000, card: 3000 });
  ok(обоими.ok && обоими.change === 0,
     '★ Считаем ОТ ВНЕСЁННОГО: карта плюс наличные');
}

// ── СМЕШАННАЯ ──────────────────────────────────────────────────────
console.log('\n═══ СМЕШАННАЯ ОПЛАТА ═══\n');
{
  const r = planMixed(5000, 3000);
  ok(r.ok && r.card === 3000 && r.cashNeeded === 2000,
     '★ Картой 3 000, наличными добрать 2 000');

  const много = planMixed(5000, 6000);
  ok(!много.ok && /больше суммы чека/.test(много.said),
     '★ Картой больше чека — отказ: банк вернул бы лишнее через три дня');

  ok(planMixed(5000, 0).cashNeeded === 5000, 'Ноль картой — всё наличными');
  ok(planMixed(5000, 5000).cashNeeded === 0, 'Всё картой — наличных не надо');
}

// ── СБОРКА ЧЕКА ────────────────────────────────────────────────────
console.log('\n═══ ЧЕК К ОТПРАВКЕ ═══\n');
{
  const cart = [];
  addToCart(cart, { id: 'g1', name: 'Водка', price: 3200, marked: true }, 1, newId);
  cart[0].codes = ['МАРКА-1'];
  addToCart(cart, { id: 'g2', name: 'Хлеб', price: 250 }, 2, newId);

  const state = {
    lastNumber: 56, storeName: 'Мини-маркет', registerName: 'Касса 1',
    employee: { id: 'e1', name: 'Айгуль' }, shift: { id: 's1' },
  };
  const due = cartTotal(cart);
  const r = buildReceipt({ cart, cartDiscount: 0, way: 'cash',
    cash: 4000, card: 0, due, state, newId });

  ok(r.number === 57, '★ Номер чека — следующий за прошлым');
  ok(r.cashierId === 'e1' && r.cashier === 'Айгуль',
     '★ В чеке КЛЮЧ кассира, а не только имя: двух Айгуль за год бывает');
  ok(r.store === 'Мини-маркет' && r.register === 'Касса 1',
     'И где пробит: у владельца магазинов несколько');
  ok(r.items[0].marks.length === 1,
     '★ Марки едут в чеке: по ним товар выходит из оборота');
  ok(r.change === 4000 - due, `Сдача посчитана: ${r.change} ₸`);
  ok(r.cashDelta === 4000 - r.change,
     '★ В ящик легло внесённое МИНУС сдача, а не вся купюра');
  ok(r.shiftId === 's1', 'Чек привязан к смене');
}

// ── КАССА ПОМНИТ СПОСОБ ────────────────────────────────────────────
{
  ok(lastWay({ lastWay: 'card' }) === 'card',
     '★ Касса помнит: в этом магазине берут картой');
  ok(lastWay({}) === 'cash', 'По умолчанию наличные');
  ok(lastWay({ lastWay: 'ерунда' }) === 'cash',
     'Мусор в настройке не роняет: берём наличные');
}

// ── СПОСОБЫ ────────────────────────────────────────────────────────
{
  const наличные = WAYS.filter((w) => w.cash).map((w) => w.id);
  ok(наличные.includes('cash') && наличные.includes('mixed'),
     '★ Помечено, где нужны наличные: там показываем купюры и сдачу');
  ok(!WAYS.find((w) => w.id === 'card').cash,
     'А картой сдачи не бывает');
}

console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
process.exit(failed ? 1 : 0);
