/*
 * ПРОВЕРКА ВОЗВРАТОВ.
 *
 * Здесь деньги уходят ИЗ кассы — самое опасное место смены.
 */
const { REASONS, MOVE_NAME, orderReasons, rememberReason, planRefund,
  cashEnough, buildRefund, buildCashMove, checkMove } = require('../renderer/refund.js');

let passed = 0, failed = 0;
const ok = (c, n) => { if (c) { passed++; console.log('✔ ' + n); } else { failed++; console.log('✘ ' + n); } };
let ln = 0; const newId = () => `r${++ln}`;

/* Чек: три пачки молока и хлеб, со скидкой на чек. */
const чек = {
  id: 'rec-1', number: 57,
  items: [
    { productId: 'g1', name: 'Молоко 2,5%', qty: 3, price: 480, discount: 0, marks: [] },
    { productId: 'g2', name: 'Хлеб', qty: 1, price: 250, discount: 0, marks: [] },
  ],
  discount: 169,      // скидка на чек
  total: 1521,        // 1440 + 250 − 169
};

const state = {
  lastNumber: 60, storeName: 'Мини-маркет', registerName: 'Касса 1',
  employee: { id: 'e1', name: 'Айгуль' }, shift: { id: 's1' }, cashInDrawer: 45000,
};

console.log('═══ ЭТАП 19 · ВОЗВРАТЫ ═══\n');

// ── ПРИЧИНЫ ────────────────────────────────────────────────────────
{
  ok(REASONS.length === 4 && REASONS.every((r) => /[а-яё]/i.test(r)),
     `Причины по-русски: ${REASONS.join(', ')}`);

  const свежие = orderReasons(['Брак или срок']);
  ok(свежие[0] === 'Брак или срок',
     '★ Недавняя причина ПЕРВОЙ: привезли кислое молоко — вернут десять раз до обеда');
  ok(свежие.length === REASONS.length, 'И остальные на месте, без задвоения');

  const п = rememberReason(['Ошибка кассира'], 'Брак или срок');
  ok(п[0] === 'Брак или срок' && п.length === 2, 'Причина запомнена');
  ok(rememberReason(['а', 'б', 'в', 'г'], 'д').length === 3,
     'Помним три последних: длинный список — тот же поиск');
}

// ── ЧАСТИЧНЫЙ ВОЗВРАТ СО СКИДКОЙ ───────────────────────────────────
console.log('\n═══ СКОЛЬКО ВЕРНУТЬ ═══\n');
{
  // Возвращают одну пачку молока из трёх
  const p = planRefund(чек, [1, 0]);
  ok(p.ok && p.items.length === 1 && p.items[0].refundQty === 1,
     '★ Частичный возврат: одна пачка из трёх');

  /* Молоко 480. Доля от чека: 480 / 1690 = 28,4%.
     Скидка чека 169 × 28,4% = 48. Вернуть 480 − 48 = 432. */
  ok(p.total === 432,
     `★ Скидка возвращается СОРАЗМЕРНО: ${p.total} ₸, а не 480`);
  ok(p.cartDiscount === 48, 'Часть скидки чека посчитана');
  ok(!p.full, 'И помечено, что возврат частичный');
}

// ── ПОЛНЫЙ ВОЗВРАТ ─────────────────────────────────────────────────
{
  const p = planRefund(чек, [3, 1]);
  ok(p.full, 'Вернули всё — помечено');
  ok(p.total === чек.total,
     `★ Полный возврат равен чеку: ${p.total} ₸ — ни больше, ни меньше`);
}

// ── НЕЧЕГО ВОЗВРАЩАТЬ ──────────────────────────────────────────────
{
  ok(!planRefund(чек, [0, 0]).ok, 'Ничего не выбрано — отказ');
  ok(!planRefund(null).ok, 'Чека нет — отказ');

  /* ПРАВИЛО СТАЛО СТРОЖЕ. Раньше просьбу вернуть 99 из 3 молча урезали
     до трёх — кассир отдал бы меньше денег, чем обещал покупателю, и
     разбирались бы у прилавка. Теперь честный отказ с числом. */
  const p = planRefund(чек, [99, 0]);
  ok(!p.ok && /можно вернуть только 3/.test(p.said),
     `★ Больше купленного не вернуть, и сказано сколько: «${p.said}»`);
}

// ── ХВАТИТ ЛИ ДЕНЕГ В ЯЩИКЕ ────────────────────────────────────────
console.log('\n═══ ДЕНЬГИ В ЯЩИКЕ ═══\n');
{
  ok(cashEnough(45000, 1521).ok, 'В ящике хватает');

  const мало = cashEnough(3000, 5000);
  ok(!мало.ok && мало.short === 2000,
     '★ Не хватает 2 000 — сказано ЗАРАНЕЕ, до «сейчас верну»');
  ok(/верните на карту/.test(мало.said),
     `И подсказан выход: «${мало.said.slice(-30)}»`);
}

// ── ЧЕК ВОЗВРАТА ───────────────────────────────────────────────────
{
  const p = planRefund(чек, [1, 0]);
  const r = buildRefund({ plan: p, receipt: чек, reason: 'Брак или срок',
    way: 'cash', state, approval: { approvedBy: 'e2', approvedName: 'Ерлан' }, newId });

  ok(r.isRefund === true, '★ Помечен как возврат: не спутать с продажей');
  ok(r.ofReceiptNumber === 57,
     '★ Ссылается на чек №57: без этого возврат не сверить с продажей');
  ok(r.cashDelta === -432,
     '★ Из ящика УШЛО, со знаком минус: сверка сойдётся сама');
  ok(r.reason === 'Брак или срок', 'Причина в чеке — она ляжет в отчёт владельца');
  ok(r.approvedName === 'Ерлан', '★ И кто разрешил: владелец спросит с него');
  ok(r.cashierId === 'e1', 'И кто пробил');
  ok(/14 дней/.test(r.returnNote), 'На чеке написано правило обмена');
}

// ── ВОЗВРАТ НА КАРТУ ───────────────────────────────────────────────
{
  const p = planRefund(чек, [1, 0]);
  const r = buildRefund({ plan: p, receipt: чек, reason: 'Товар не подошёл',
    way: 'card', state, approval: {}, newId });
  ok(r.cashDelta === 0 && r.card === 432,
     '★ Возврат на карту ящик не трогает: деньги идут через банк');
}

// ── ПОДПИСЬ БЕЗ СВЯЗИ ──────────────────────────────────────────────
{
  const p = planRefund(чек, [1, 0]);
  const r = buildRefund({ plan: p, receipt: чек, reason: 'Ошибка кассира',
    way: 'cash', state, newId,
    approval: { approvedBy: null, approvedName: 'без проверки',
      offlineNote: 'без связи, код старшего не проверен' } });

  ok(/не проверен/.test(r.offlineNote),
     '★ Пометка «без связи» дошла до чека: владелец увидит, что подпись не проверена');
}

// ── ДВИЖЕНИЕ ДЕНЕГ ─────────────────────────────────────────────────
console.log('\n═══ ВНЕСЕНИЕ И ИЗЪЯТИЕ ═══\n');
{
  const внёс = buildCashMove({ kind: 'cash_in', amount: 20000, note: 'размен из сейфа',
    state, approval: {}, newId });
  ok(внёс.cashDelta === 20000, 'Внесение прибавляет в ящик');

  const изъял = buildCashMove({ kind: 'cash_out', amount: 30000, note: 'владелец забрал',
    state, approval: { approvedName: 'Нурлан' }, newId });
  ok(изъял.cashDelta === -30000, '★ Изъятие убавляет — со знаком минус');
  ok(изъял.approvedName === 'Нурлан',
     '★ И кто разрешил: без этого кассир объясняется за чужие деньги');

  const инк = buildCashMove({ kind: 'collection', amount: 100000, state, approval: {}, newId });
  ok(инк.cashDelta === -100000 && MOVE_NAME.collection === 'Инкассация',
     'Инкассация — тоже изъятие, но названа по-своему');
}

// ── БОЛЬШЕ, ЧЕМ ЕСТЬ, НЕ ИЗЪЯТЬ ────────────────────────────────────
{
  ok(checkMove('cash_out', 50000, 45000).ok === false,
     '★ Изъять больше, чем в ящике, нельзя: он ушёл бы в минус');
  ok(/В ящике всего 45000/.test(checkMove('cash_out', 50000, 45000).said),
     'И сказано, сколько есть');

  ok(checkMove('cash_in', 50000, 45000).ok,
     'А внести можно сколько угодно: деньги приносят из сейфа');
  ok(!checkMove('cash_out', 0, 45000).ok, 'Ноль — не сумма');
  ok(!checkMove('cash_out', -100, 45000).ok, 'Отрицательное — отказ');
}

// ── ДЕНЬГИ ДВАЖДЫ НЕ ОТДАЁМ ────────────────────────────────────────
{
  /* Чек могли принести ВТОРОЙ раз: часть уже возвращали. Без этой
     проверки магазин платит дважды за один товар. */
  const чек = (returned) => ({ id: 'r1', number: 57,
    items: [{ productId: 'g1', name: 'Молоко', qty: 2, price: 480, discount: 0, returned }] });

  ok(planRefund(чек(0), [2]).ok, 'Ничего не возвращали — можно всё');

  const дважды = planRefund(чек(1), [2]);
  ok(!дважды.ok && /можно вернуть только 1/.test(дважды.said),
     `★ Одну уже вернули — две не отдадим: «${дважды.said}»`);

  const остаток = planRefund(чек(1), [1]);
  ok(остаток.ok && остаток.total === 480,
     '★ А оставшуюся пачку вернуть можно: 480 ₸');

  const всё = planRefund(чек(2), [1]);
  ok(!всё.ok && /уже всё возвращено/.test(всё.said),
     '★ Вернули всё — второй раз денег нет');
}

console.log(`\n=== ИТОГ: пройдено ${passed}, провалено ${failed} ===`);
process.exit(failed ? 1 : 0);
