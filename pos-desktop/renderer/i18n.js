/** Выбранный язык. По умолчанию русский: на нём говорят все. */
function posLang() {
  try { return localStorage.getItem('tabys.posLang') === 'kk' ? 'kk' : 'ru'; }
  catch { return 'ru'; }
}

/** Переключить язык. Перезагрузка не нужна — экран перерисуется. */
function setPosLang(lang) {
  try { localStorage.setItem('tabys.posLang', lang === 'kk' ? 'kk' : 'ru'); }
  catch { /* хранилище тесно — язык не запомнится, но смена сработает */ }
}

/* Слово по ключу. Нет перевода — берём русский, нет и его — сам ключ:
   лучше английское слово на экране, чем пустое место. */
function tt(key) {
  const l = posLang();
  return (POS_WORDS[l] && POS_WORDS[l][key]) || POS_WORDS.ru[key] || key;
}
