/**
 * ОШИБКИ ЧЕЛОВЕЧЕСКИМИ СЛОВАМИ — по образцу их ui/errors.ts.
 *
 * Их довод: сервер отвечает кодом — это правильно, код не зависит от
 * языка и не ломается при переводе. Но показывать человеку
 * {"code":"PHONE_TAKEN"} нельзя, поэтому перевод живёт в одном месте.
 *
 * У НАС ИНАЧЕ, И ЭТО ЛУЧШЕ: сервер уже отвечает по-русски
 * («Подтверждает только владелец платформы»). Здесь остаётся разбор
 * того, что человеческим текстом не приходит: обрыв связи, отказ
 * доступа, ответ не в том виде.
 */
const BY_STATUS: Record<number, string> = {
  400: 'Данные не подошли — проверьте, что заполнено',
  401: 'Вход истёк. Войдите заново',
  403: 'Нет доступа: это решает владелец платформы',
  404: 'Не нашлось — возможно, уже удалено',
  409: 'Кто-то успел раньше. Обновите страницу и попробуйте снова',
  429: 'Слишком много попыток. Подождите минуту',
  500: 'Сервер не справился. Данные не потеряны — попробуйте ещё раз',
  502: 'Сервер перезапускается. Через минуту всё вернётся',
  503: 'Сервер перезапускается. Через минуту всё вернётся',
};

/** Понятная строка из чего угодно, что прилетело в catch. */
export function humanError(e: unknown): string {
  if (!e) return 'Что-то пошло не так';

  const msg = e instanceof Error ? e.message : String(e);

  // Обрыв связи. Главное здесь — сказать, что данные целы: человек
  // боится, что его правка пропала.
  if (/Failed to fetch|NetworkError|network|ERR_INTERNET/i.test(msg))
    return 'Нет связи с сервером. Данные не потеряны — проверьте интернет и повторите';

  // Наш сервер отвечает по-русски: такое показываем как есть.
  if (/[а-яё]/i.test(msg)) return msg;

  const m = msg.match(/Ошибка (\d{3})/);
  if (m) return BY_STATUS[Number(m[1])] ?? msg;

  return msg || 'Что-то пошло не так';
}
