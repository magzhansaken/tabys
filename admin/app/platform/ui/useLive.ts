'use client';
/**
 * САМООБНОВЛЕНИЕ РАЗДЕЛА — по образцу их refetchInterval.
 *
 * Их приём, которого у меня не было: разделы, где ждут действий,
 * обновляются сами. Оплаты и заявки — каждые 20 секунд, списки
 * клиентов — каждые 30.
 *
 * Зачем: панель держат открытой весь день. Партнёр отметил оплату —
 * владелец должен увидеть её, не нажимая ничего. Иначе он сидит перед
 * пустой лентой, пока клиент ждёт продления.
 *
 * ЧЕГО НЕ ДЕЛАЕМ: не обновляем сводку, воронку и журнал. Там смотрят
 * картину, а не ждут событий, и цифры, меняющиеся под рукой, мешают
 * читать.
 *
 * НЕ ОБНОВЛЯЕМ, КОГДА ВКЛАДКА НЕ ВИДНА: незачем дёргать сервер, пока
 * человек в другом окне. И не обновляем, пока открыт лист
 * подтверждения — данные под ним меняться не должны.
 */
import { useEffect, useRef } from 'react';

export function useLive(fn: () => void, ms = 20_000) {
  const saved = useRef(fn);
  saved.current = fn;

  useEffect(() => {
    const tick = () => {
      // Вкладка не видна — пропускаем: человек в другом окне.
      if (document.visibilityState !== 'visible') return;
      // Открыт лист подтверждения — данные под ним меняться не должны.
      if (document.querySelector('.modal')) return;
      saved.current();
    };
    const t = window.setInterval(tick, ms);
    return () => window.clearInterval(t);
  }, [ms]);
}
